"""Non-element XML nodes retain bytes while layout resource checks stay active."""
import io
import unittest
import zipfile

from . import layout_source as source, word_v3 as w


W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
A = 'http://schemas.openxmlformats.org/drawingml/2006/main'
R = 'http://schemas.openxmlformats.org/package/2006/relationships'
BENIGN = '<!-- Generated by Aspose.Words FOSS for .NET 26.3.0 -->'


def package(body='', theme='', relations='', annotations=BENIGN):
    """Only synthetic XML: real original/export qualification stays in evidence."""
    document = (f'<w:document xmlns:w="{W}">{annotations}<w:body>'
                f'<w:p><w:r><w:rPr><w:rFonts w:ascii="Arial"/></w:rPr>'
                f'<w:t>Question and existing answer</w:t></w:r>{annotations}{body}</w:p>'
                f'<w:sectPr/></w:body></w:document>')
    theme_xml = f'<a:theme xmlns:a="{A}">{annotations}<a:latin typeface="Aptos"/>{theme}</a:theme>'
    rels = f'<Relationships xmlns="{R}">{annotations}{relations}</Relationships>'
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w') as archive:
        archive.writestr('word/document.xml', document)
        archive.writestr('word/theme/theme1.xml', theme_xml)
        archive.writestr('word/_rels/document.xml.rels', rels)
        archive.writestr('word/header1.xml', f'<w:hdr xmlns:w="{W}">{annotations}<w:p/></w:hdr>')
        archive.writestr('word/footer1.xml', f'<w:ftr xmlns:w="{W}">{annotations}<w:p/></w:ftr>')
        archive.writestr('opaque-retained.bin', b'\x00exact unchanged non-XML bytes\xff')
    return w.Package(buffer.getvalue())


def snapshot(original):
    return {'source': original.data, 'zip_bytes': original.zip.fp.getvalue(),
            'names': list(original.names),
            'part_bytes': {n: original.zip.read(n) for n in original.names},
            'trees': {n: w.etree.tostring(original.tree(n).getroottree()) for n in original.names
                      if n.endswith(('.xml', '.rels'))}}


class LayoutSourceNodes(unittest.TestCase):
    def check(self, original, expected_fonts=None, rejected=False):
        before = snapshot(original)
        if rejected:
            with self.assertRaises(w.V3Failure) as error:
                source.safety(original)
            self.assertEqual(error.exception.code, 'layout_unsafe_source')
        else:
            self.assertEqual(source.safety(original), expected_fonts or ['Aptos', 'Arial'])
        self.assertEqual(snapshot(original), before)

    def test_retained_comments_preserve_source_and_fonts(self):
        for annotation in ('<!-- harmless annotation -->', BENIGN):
            with self.subTest(annotation=annotation):
                current = package(annotations=annotation)
                nodes = [n for name in current.names if name.endswith('.xml')
                         for n in current.tree(name).iter() if not isinstance(n.tag, str)]
                self.assertTrue(nodes)
                self.assertTrue(all(isinstance(n, w.etree._Comment) for n in nodes))
                self.check(current)
        self.check(package(annotations=''))

    def test_resource_field_elements_are_checked_around_non_element_nodes(self):
        for command in ('INCLUDETEXT', 'INCLUDEPICTURE', 'DDE', 'DDEAUTO', 'LINK', 'DATABASE'):
            for annotation_first in (True, False):
                with self.subTest(command=command, annotation_first=annotation_first):
                    field = f'<w:r><w:instrText>{command} source</w:instrText></w:r>'
                    body = BENIGN + field if annotation_first else field + BENIGN
                    self.check(package(body=body), rejected=True)
        self.check(package(body='<w:r><w:instrText>MERGEFIELD ordinary</w:instrText></w:r>'))

    def test_external_resources_and_attached_templates_stay_refused(self):
        for kind, mode in (('attachedTemplate', ''), ('image', 'External'), ('oleObject', 'External')):
            with self.subTest(kind=kind):
                rel = (f'<Relationship Id="r1" Type="http://schemas.openxmlformats.org/'
                       f'officeDocument/2006/relationships/{kind}" Target="https://invalid.test/resource" '
                       f'TargetMode="{mode}"/>')
                self.check(package(relations=rel), rejected=True)
        allowed = ('<Relationship Id="r1" Type="http://schemas.openxmlformats.org/'
                   'officeDocument/2006/relationships/hyperlink" Target="https://invalid.test/link" '
                   'TargetMode="External"/>')
        self.check(package(relations=allowed))

    def test_embedded_font_program_elements_stay_refused(self):
        for kind in ('embedRegular', 'embedBold', 'embedItalic', 'embedBoldItalic'):
            with self.subTest(kind=kind):
                self.check(package(body=BENIGN + f'<w:{kind}/>' + BENIGN), rejected=True)

    def test_theme_fonts_and_font_bounds_are_not_skipped(self):
        self.check(package(theme=BENIGN + '<a:latin typeface="Courier New"/>'),
                   expected_fonts=['Aptos', 'Arial', 'Courier New'])
        for theme in ('<a:latin typeface="' + 'A' * 201 + '"/>',
                      ''.join(f'<a:latin typeface="font{i}"/>' for i in range(201))):
            with self.subTest(theme_length=len(theme)):
                self.check(package(theme=BENIGN + theme), rejected=True)

    def test_comment_text_is_not_mistaken_for_active_resource_elements(self):
        self.check(package(annotations='<!-- DDE INCLUDETEXT or embeddedFont is only annotation -->'))

    def test_PI_uses_controlled_unsupported_refusal_without_changing_source(self):
        for annotation in ('<?review untouched?>', '<?xml-stylesheet href="https://invalid.test/style"?>',
                           '<?synthetic INCLUDEPICTURE is PI text?>'):
            with self.subTest(annotation=annotation):
                current = package(annotations=annotation)
                self.assertTrue(any(isinstance(n, w.etree._ProcessingInstruction)
                                    for n in current.tree('word/document.xml').iter()))
                self.check(current, rejected=True)

    def test_complete_XML_document_checks_PI_and_preserves_comments_at_all_positions(self):
        for part in ('word/document.xml', 'word/theme/theme1.xml', 'word/_rels/document.xml.rels'):
            for position in ('prolog', 'body', 'epilog'):
                for annotation, rejected in ((BENIGN, False), ('<?xml-stylesheet href="https://invalid.test/style"?>', True)):
                    with self.subTest(part=part, position=position, rejected=rejected):
                        current = package(annotations='')
                        root = current.tree(part)
                        node = w.etree.fromstring(f'<wrapper>{annotation}</wrapper>'.encode())[0]
                        if position == 'prolog':
                            root.addprevious(node)
                        elif position == 'epilog':
                            root.addnext(node)
                        else:
                            root.append(node)
                        self.check(current, rejected=rejected)

    def test_multiple_siblings_cannot_hide_PI_behind_retained_comments(self):
        for pi_before in (True, False):
            current = package(annotations='')
            root = current.tree('word/document.xml')
            root.addprevious(w.etree.Comment('first retained comment'))
            root.addnext(w.etree.Comment('last retained comment'))
            pi = w.etree.ProcessingInstruction('xml-stylesheet', 'href="https://invalid.test/style"')
            if pi_before:
                root.getprevious().addprevious(pi)
            else:
                root.getnext().addnext(pi)
            self.check(current, rejected=True)

    def test_other_non_string_XML_nodes_do_not_get_comment_exemption(self):
        raw = (f'<!DOCTYPE document [<!ENTITY source "unresolved">]><w:document xmlns:w="{W}">'
               '<w:body><w:p>&source;</w:p></w:body></w:document>').encode()
        current = package()
        tree = w.etree.fromstring(raw, w.PARSER)
        self.assertTrue(any(isinstance(node, w.etree._Entity) for node in tree.iter()))
        current.trees['word/document.xml'] = tree
        # Public upload separately forbids DTD/entities. Even a constructed
        # package outside that admission path must fail closed here.
        self.check(current, rejected=True)
