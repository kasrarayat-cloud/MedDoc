FORM_ID = 'synthetic-colonoscopy-voice-v1'
FORM_SHA256 = '1d2240c577e2472f25521e9c59fdb8d10ab109b514fc4aa043db095ee309fd8e'
MANIFEST_SHA256 = '64fed2b82500f1bc9f8533eb28da27c75abfbacb3b2c91d6c7184846df6a3381'
MANIFEST = Path(__file__).with_name('fixtures') / 'synthetic-colonoscopy-voice-v1.json'
