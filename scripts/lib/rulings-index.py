#!/usr/bin/env python3
# =============================================================================
# RULINGS-INDEX — regenerate the live index of RULINGS.md FROM its archives.
# -----------------------------------------------------------------------------
# ⚠️ WHY THIS EXISTS. The 2026-08-26 split moved every ruling BODY into
# `docs/foundation/rulings/` and left a hand-written index behind. The rows were
# truncated at 72 characters, which silently removed the STATUS marker from the
# end of every title — and the status marker is the thing the mandated routes
# grep for. Measured on the split head before this generator:
#
#     grep -c 'OWNER RULING' docs/foundation/RULINGS.md   ->  0   (main: 23)
#     grep -c PROVISIONAL    docs/foundation/RULINGS.md   ->  1   (main: 47)
#
# `AGENTS.md` orders *"BEFORE DECIDING ANYTHING RULING-SHAPED, GREP
# docs/foundation/RULINGS.md"*, and `MASTER.md` orders the morning report's
# PROVISIONAL block reconstructed FROM DISK out of that file. A zero there does
# not read as "the index is truncated". It reads as "there are none".
#
# ── THE CONTRACT THIS FILE KEEPS ────────────────────────────────────────────
# Every row carries, as SEPARATE greppable cells:
#     · the ruling NUMBER   (`#127`)      — so a citation resolves on the head
#     · the STATUS TOKEN    (`PROVISIONAL`) in a column of its own, so
#       `grep '| PROVISIONAL |'` returns the TRUE count and cannot be inflated
#       by the word appearing inside a title or a verdict
#     · a short TITLE       — enough to recognise the ruling
#
# ⚠️ THE ARCHIVE IS THE AUTHORITY, THE ROW IS A POINTER. That is the file's own
# standing rule, so this generator reads DOWN from the archives and never up
# from the index. A hand-edited row cannot drift from its body, because a
# hand-edited row does not survive the next run.
#
# ⚠️ IT REPLACES, IT NEVER PREPENDS — canon: a regeneration that prepends leaves
# a file holding every value you assert, syntactically dead, newest on top
# reading as the only one. The marker pair is the delete boundary and it is
# asserted after the write.
#
# EXIT CODES
#   0  index regenerated (or, with --check, the index is already correct)
#   1  with --check: the index is STALE — regenerate it
#   2  CANNOT TELL — fail-closed. Unreadable archives, no rows parsed,
#      a census that does not reconcile. Never treated as "nothing to do".
# =============================================================================
import io, os, re, sys, glob

BEGIN = "<!-- RULINGS-INDEX-BEGIN — generated by scripts/lib/rulings-index.py; do not hand-edit -->"
END   = "<!-- RULINGS-INDEX-END -->"

ROOT     = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RULINGS  = os.path.join(ROOT, "docs", "foundation", "RULINGS.md")
ARCHDIR  = os.path.join(ROOT, "docs", "foundation", "rulings")

TITLE_MAX = 96


def die(msg):
    print("🔴 rulings-index: CANNOT TELL — " + msg)
    raise SystemExit(2)


def cells(line):
    """Split a markdown table row, honouring the escaped pipe `\\|`."""
    parts, buf, i = [], [], 0
    while i < len(line):
        c = line[i]
        if c == "\\" and i + 1 < len(line) and line[i + 1] == "|":
            buf.append("|"); i += 2; continue
        if c == "|":
            parts.append("".join(buf)); buf = []; i += 1; continue
        buf.append(c); i += 1
    parts.append("".join(buf))
    return [p.strip() for p in parts]


def status_of(text):
    """One token per row. ORDER IS THE RULING, not a convenience:
    an owner ruling that was later ratified is still an OWNER RULING — the
    authority is the point, and it is the question a session actually asks
    ('may I overturn this?'). Ratified-by-the-owner outranks provisional for
    the same reason."""
    if "OWNER RULING" in text:  return "OWNER-RULING"
    if "RATIFIED" in text:      return "RATIFIED"
    if "SUPERSEDED" in text:    return "SUPERSEDED"
    if "PROVISIONAL" in text:   return "PROVISIONAL"
    return "RECORDED"


NUM_RE   = re.compile(r"\*\*#(\d+)\b")
CLEAN_RE = re.compile(r"\*\*|__|`")


def short_title(ruling_cell):
    t = ruling_cell
    t = NUM_RE.sub("", t, count=1)
    t = re.sub(r"^\s*[—–-]\s*", "", CLEAN_RE.sub("", t)).strip()
    # the status marker lives at the END of the title on the source rows; it has
    # its own column now, so drop the trailing marker rather than print it twice
    t = re.split(r"\s+—\s+(?:✅|🟡|⚠️|🔴)", t)[0].strip()
    if len(t) > TITLE_MAX:
        t = t[: TITLE_MAX - 1].rstrip() + "…"
    return t.replace("|", "\\|")


def main():
    check = "--check" in sys.argv[1:]

    if not os.path.isdir(ARCHDIR):
        die("%s does not exist. The index is generated FROM the archives; with no "
            "archives there is nothing to generate and this is not 'no rows'." % ARCHDIR)

    rows = []
    for path in sorted(glob.glob(os.path.join(ARCHDIR, "*.md"))):
        name = os.path.basename(path)
        if name == "README.md":
            continue
        try:
            body = io.open(path, encoding="utf-8").read()
        except OSError as e:
            die("cannot read %s (%s)" % (name, e))
        for line in body.split("\n"):
            if not line.startswith("| 20"):
                continue
            c = cells(line)
            if len(c) < 4:
                continue
            date, ruling, verdict = c[1], c[2], c[3]
            m = NUM_RE.search(ruling)
            rows.append({
                "date": date,
                "num": ("#" + m.group(1)) if m else "—",
                "status": status_of(ruling + " " + verdict),
                "title": short_title(ruling),
                "verdict": (verdict[:110].rstrip() + "…") if len(verdict) > 110 else verdict,
                "archive": name,
            })

    # ── NON-VACUITY FLOOR, BEFORE ANY VERDICT IS BELIEVED ────────────────────
    # A parser that matched nothing would emit a perfectly well-formed EMPTY
    # index and every downstream count would reconcile at zero.
    if len(rows) < 50:
        die("parsed only %d rows from %d archives — a matcher that reads nothing "
            "produces an index that is wrong in the one direction nobody checks."
            % (len(rows), len(glob.glob(os.path.join(ARCHDIR, '*.md')))))

    counts = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    if sum(counts.values()) != len(rows):
        die("status partition does not reconcile: %d != %d" % (sum(counts.values()), len(rows)))

    out = [BEGIN, ""]
    out.append("> **Generated by `scripts/lib/rulings-index.py`. Do not hand-edit between the")
    out.append("> markers — the generator REPLACES this block, so a hand edit does not survive.**")
    out.append(">")
    out.append("> ⚠️ **A ROW IS A POINTER, NEVER THE RULING.** If a row and its archived body")
    out.append("> disagree, **the body is right and the row is the defect** — and the fix is to")
    out.append("> correct the body and re-run this, never to edit the row.")
    out.append(">")
    out.append("> **THE STATUS COLUMN EXISTS SO A GREP RETURNS A TRUE COUNT.** Grep the PIPED")
    out.append("> form of the token — a bare word is also counted where it appears inside")
    out.append("> somebody's prose, and the piped form is only ever a row:")
    out.append(">")
    out.append(">     grep -c '[|] PROVISIONAL [|]' docs/foundation/RULINGS.md")
    out.append(">")
    out.append("> ⚠️ **The example above writes the pipes as `[|]` DELIBERATELY.** Written")
    out.append("> literally it would be a row-shaped string inside the index, and this")
    out.append("> generator's own post-write census would count it — a probe that matches")
    out.append("> itself. It caught exactly that on its first run.")
    out.append(">")
    out.append("> ⚠️ **AND THE HEAD IS NOT THE WHOLE FILE.** A grep for a ruling's REASONING")
    out.append("> must read the archives too:")
    out.append(">")
    out.append(">     grep -n '<what you want>' docs/foundation/RULINGS.md docs/foundation/rulings/*.md")
    out.append(">")
    out.append("> The head answers *which ruling and what status*. The archive answers *why*.")
    out.append("")
    out.append("**%d rulings.** %s" % (
        len(rows),
        " · ".join("**%d %s**" % (counts[k], k) for k in
                   ["OWNER-RULING", "RATIFIED", "PROVISIONAL", "SUPERSEDED", "RECORDED"]
                   if k in counts)))
    out.append("")
    out.append("| date | # | status | ruling | verdict, in one line | full body |")
    out.append("|---|---|---|---|---|---|")
    for r in rows:
        out.append("| %s | %s | %s | %s | %s | [`%s`](rulings/%s) |" % (
            r["date"], r["num"], r["status"], r["title"],
            r["verdict"].replace("|", "\\|"), r["archive"], r["archive"]))
    out += ["", END]
    block = "\n".join(out)

    src = io.open(RULINGS, encoding="utf-8").read()
    i, j = src.find(BEGIN), src.find(END)
    if (i >= 0) != (j >= 0):
        die("exactly one index marker is present — refusing to guess the boundary")
    if i >= 0:
        new = src[:i] + block + src[j + len(END):]
    else:
        # FIRST RUN: replace the hand-written table between '## The index' and the
        # next top-level heading. Anchored on BOTH ends — a one-ended anchor that
        # slips eats the rest of the file.
        a = src.find("\n## The index")
        if a < 0:
            die("no '## The index' section and no markers — nothing to anchor on")
        b = src.find("\n## ", a + 1)
        if b < 0:
            die("'## The index' has no following section — refusing to write to EOF")
        new = src[:a] + "\n## The index\n\n" + block + "\n" + src[b:]

    if check:
        if new == src:
            print("🟢 rulings-index: index is current — %d rows, %s" % (
                len(rows), ", ".join("%s %d" % (k, v) for k, v in sorted(counts.items()))))
            return 0
        print("🟡 rulings-index: index is STALE. Run: python3 scripts/lib/rulings-index.py")
        return 1

    io.open(RULINGS, "w", encoding="utf-8").write(new)

    # ── PROVE THE APPLICATION. Never trust the write. ────────────────────────
    chk = io.open(RULINGS, encoding="utf-8").read()
    if chk.count(BEGIN) != 1 or chk.count(END) != 1:
        die("head has %d index blocks after write — the generator appended instead "
            "of replacing" % chk.count(BEGIN))
    for k, v in counts.items():
        got = chk.count("| %s |" % k)
        if got != v:
            die("post-write census failed for %s: wrote %d rows, grep finds %d" % (k, v, got))
    print("🟢 rulings-index: %d rows regenerated · %s" % (
        len(rows), " · ".join("%s %d" % (k, v) for k, v in sorted(counts.items()))))
    print("   post-write greps (the mandated routes, measured):")
    for k in sorted(counts):
        print("     grep -c '| %s |' -> %d" % (k, chk.count("| %s |" % k)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
