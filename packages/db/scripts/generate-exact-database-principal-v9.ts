#!/usr/bin/env tsx

// Generates the plan-independent structural half of the additive v9 catalog
// closure. The unchanged runtime-protocol manifest is the immediate external
// post-migration gate because embedding its deparsers changes their context.

import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const outputPath = fileURLToPath(
  new URL(
    "../prisma/migrations/20260720213000_exact_database_principal_closure_v9/migration.sql",
    import.meta.url,
  ),
);
function generate(): string {
  return `-- Exact PostgreSQL principal/catalog closure v9.
--
-- Generated by packages/db/scripts/generate-exact-database-principal-v9.ts
-- as the plan-independent structural half of the exact runtime catalog proof.
-- Do not hand-edit this migration.
-- The durable helper exposes only a fixed-role credential-attestation boolean
-- to the six NOLOGIN boundaries. It never returns a verifier. Its source,
-- owner, ACL, and configuration are part of the externally frozen application
-- and per-boundary manifests.
BEGIN;
SET LOCAL search_path = pg_catalog, public;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '180s';
SELECT pg_catalog.pg_advisory_xact_lock(73119, 2026072001);

DO $target_guard$
BEGIN
  IF pg_catalog.current_setting('server_version_num')::INTEGER
       NOT BETWEEN 160000 AND 169999
    OR NOT EXISTS (
      SELECT 1
      FROM pg_catalog.pg_database database
      JOIN pg_catalog.pg_roles owner ON owner.oid = database.datdba
      WHERE database.datname = pg_catalog.current_database()
        AND owner.rolname = current_user
        AND owner.rolsuper
    )
    OR pg_catalog.to_regprocedure(
      'public.quillmd_boundary_password_is_null(text)'
    ) IS NOT NULL
  THEN
    RAISE EXCEPTION 'Exact database-principal v9 target is not pristine';
  END IF;
END
$target_guard$;

CREATE FUNCTION public.quillmd_boundary_password_is_null(boundary_name TEXT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $password_null$
  SELECT CASE
    WHEN boundary_name IN (
      'quillmd_runtime',
      'quillmd_release_control',
      'quillmd_release_security',
      'quillmd_audit_dispatcher',
      'quillmd_auth_email_dispatcher',
      'quillmd_backup'
    ) THEN EXISTS (
      SELECT 1
      FROM pg_catalog.pg_authid authentication
      WHERE authentication.rolname = boundary_name
        AND authentication.rolcanlogin = FALSE
        AND authentication.rolpassword IS NULL
    )
    WHEN boundary_name IN (
      'meddoc_runtime',
      'meddoc_release_control',
      'meddoc_release_security',
      'meddoc_audit_dispatcher',
      'meddoc_auth_email_dispatcher',
      'meddoc_backup'
    ) THEN EXISTS (
      SELECT 1
      FROM pg_catalog.pg_authid authentication
      WHERE authentication.rolname = boundary_name
        AND authentication.rolcanlogin = TRUE
        AND authentication.rolpassword LIKE 'SCRAM-SHA-256$4096:%'
    )
    ELSE FALSE
  END;
$password_null$;
REVOKE ALL ON FUNCTION
  public.quillmd_boundary_password_is_null(TEXT)
FROM PUBLIC;
GRANT EXECUTE ON FUNCTION
  public.quillmd_boundary_password_is_null(TEXT)
TO
  quillmd_runtime,
  quillmd_release_control,
  quillmd_release_security,
  quillmd_audit_dispatcher,
  quillmd_auth_email_dispatcher,
  quillmd_backup;

DO $exact_role_graph$
DECLARE
  controlled_roles CONSTANT TEXT[] := ARRAY[
    'meddoc_runtime',
    'meddoc_release_control',
    'meddoc_release_security',
    'meddoc_audit_dispatcher',
    'meddoc_auth_email_dispatcher',
    'meddoc_backup',
    'quillmd_runtime',
    'quillmd_release_control',
    'quillmd_release_security',
    'quillmd_audit_dispatcher',
    'quillmd_auth_email_dispatcher',
    'quillmd_backup',
    'pg_read_all_data'
  ];
BEGIN
  IF EXISTS (
    WITH expected(
      role_name, required, can_login, inherits, bypass_rls, connection_limit,
      superuser, create_db, create_role, replication,
      valid_until_is_null, config_is_null
    ) AS (
      VALUES
        ('meddoc_runtime', TRUE, TRUE, TRUE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('meddoc_release_control', TRUE, TRUE, TRUE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('meddoc_release_security', FALSE, TRUE, TRUE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('meddoc_audit_dispatcher', TRUE, TRUE, TRUE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('meddoc_auth_email_dispatcher', TRUE, TRUE, TRUE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('meddoc_backup', TRUE, TRUE, TRUE, TRUE, 1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('quillmd_runtime', TRUE, FALSE, FALSE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('quillmd_release_control', TRUE, FALSE, FALSE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('quillmd_release_security', TRUE, FALSE, FALSE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('quillmd_audit_dispatcher', TRUE, FALSE, FALSE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('quillmd_auth_email_dispatcher', TRUE, FALSE, FALSE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('quillmd_backup', TRUE, FALSE, FALSE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE),
        ('pg_read_all_data', TRUE, FALSE, TRUE, FALSE, -1,
          FALSE, FALSE, FALSE, FALSE, TRUE, TRUE)
    ), expected_present AS (
      SELECT expected.role_name, expected.can_login, expected.inherits,
        expected.bypass_rls, expected.connection_limit, expected.superuser,
        expected.create_db, expected.create_role, expected.replication,
        expected.valid_until_is_null, expected.config_is_null
      FROM expected
      WHERE expected.required OR EXISTS (
        SELECT 1 FROM pg_catalog.pg_roles role
        WHERE role.rolname = expected.role_name
      )
    ), actual AS (
      SELECT role.rolname::TEXT, role.rolcanlogin, role.rolinherit,
        role.rolbypassrls, role.rolconnlimit, role.rolsuper,
        role.rolcreatedb, role.rolcreaterole, role.rolreplication,
        role.rolvaliduntil IS NULL, role.rolconfig IS NULL
      FROM pg_catalog.pg_roles role
      WHERE role.rolname = ANY(controlled_roles)
    )
    (SELECT * FROM actual EXCEPT ALL SELECT * FROM expected_present)
    UNION ALL
    (SELECT * FROM expected_present EXCEPT ALL SELECT * FROM actual)
  ) OR EXISTS (
    SELECT 1
    FROM pg_catalog.pg_authid authentication
    WHERE authentication.rolname = ANY(ARRAY[
      'quillmd_runtime',
      'quillmd_release_control',
      'quillmd_release_security',
      'quillmd_audit_dispatcher',
      'quillmd_auth_email_dispatcher',
      'quillmd_backup',
      'pg_read_all_data'
    ]::TEXT[])
      AND authentication.rolpassword IS NOT NULL
  ) OR EXISTS (
    SELECT 1
    FROM pg_catalog.pg_authid authentication
    WHERE authentication.rolname = ANY(ARRAY[
      'meddoc_runtime',
      'meddoc_release_control',
      'meddoc_release_security',
      'meddoc_audit_dispatcher',
      'meddoc_auth_email_dispatcher',
      'meddoc_backup'
    ]::TEXT[])
      AND (
        authentication.rolpassword IS NULL
        OR authentication.rolpassword NOT LIKE 'SCRAM-SHA-256$4096:%'
      )
  ) THEN
    RAISE EXCEPTION 'Exact database-principal role attributes are required';
  END IF;

  IF EXISTS (
    WITH expected_edges(
      member_name, granted_name, required,
      admin_option, inherit_option, set_option
    ) AS (
      VALUES
        ('meddoc_runtime', 'quillmd_runtime', TRUE, FALSE, TRUE, FALSE),
        ('meddoc_release_control', 'quillmd_release_control', TRUE, FALSE, TRUE, FALSE),
        ('meddoc_release_security', 'quillmd_release_security', FALSE, FALSE, TRUE, FALSE),
        ('meddoc_audit_dispatcher', 'quillmd_audit_dispatcher', TRUE, FALSE, TRUE, FALSE),
        ('meddoc_auth_email_dispatcher', 'quillmd_auth_email_dispatcher', TRUE, FALSE, TRUE, FALSE),
        ('meddoc_backup', 'quillmd_backup', TRUE, FALSE, TRUE, FALSE),
        ('quillmd_backup', 'pg_read_all_data', TRUE, FALSE, TRUE, FALSE)
    ), expected_present AS (
      SELECT expected_edges.*
      FROM expected_edges
      WHERE expected_edges.required OR EXISTS (
        SELECT 1 FROM pg_catalog.pg_roles role
        WHERE role.rolname = expected_edges.member_name
      )
    ), actual AS (
      SELECT member_role.rolname::TEXT AS member_name,
        granted_role.rolname::TEXT AS granted_name,
        membership.admin_option,
        membership.inherit_option,
        membership.set_option,
        grantor_role.rolsuper AS grantor_superuser
      FROM pg_catalog.pg_auth_members membership
      JOIN pg_catalog.pg_roles member_role
        ON member_role.oid = membership.member
      JOIN pg_catalog.pg_roles granted_role
        ON granted_role.oid = membership.roleid
      JOIN pg_catalog.pg_roles grantor_role
        ON grantor_role.oid = membership.grantor
      WHERE member_role.rolname = ANY(controlled_roles)
         OR granted_role.rolname = ANY(controlled_roles)
         OR grantor_role.rolname = ANY(controlled_roles)
    ), expected_normalized AS (
      SELECT member_name, granted_name, admin_option,
        inherit_option, set_option, TRUE AS grantor_superuser
      FROM expected_present
    )
    (SELECT * FROM actual EXCEPT ALL SELECT * FROM expected_normalized)
    UNION ALL
    (SELECT * FROM expected_normalized EXCEPT ALL SELECT * FROM actual)
  ) THEN
    RAISE EXCEPTION 'Exact database-principal role graph is required';
  END IF;
END
$exact_role_graph$;

-- The full deparse/ACL manifest is deliberately verified immediately after
-- this migration by the runtime-protocol PostgreSQL harness. Embedding that
-- query under a migration assertion changes PostgreSQL's deparser context.
-- Keep this transaction's postcondition explicit and plan-independent.
DO $exact_helper_contract$
DECLARE
  helper_oid OID := pg_catalog.to_regprocedure(
    'public.quillmd_boundary_password_is_null(text)'
  );
  database_owner_oid OID := (
    SELECT database.datdba
    FROM pg_catalog.pg_database database
    WHERE database.datname = pg_catalog.current_database()
  );
BEGIN
  IF helper_oid IS NULL
    OR (
      SELECT pg_catalog.count(*)
      FROM pg_catalog.pg_proc callable
      JOIN pg_catalog.pg_namespace namespace
        ON namespace.oid = callable.pronamespace
      WHERE namespace.nspname = 'public'
        AND callable.proname = 'quillmd_boundary_password_is_null'
    ) <> 1
    OR NOT EXISTS (
      SELECT 1
      FROM pg_catalog.pg_proc callable
      JOIN pg_catalog.pg_namespace namespace
        ON namespace.oid = callable.pronamespace
      JOIN pg_catalog.pg_language language
        ON language.oid = callable.prolang
      WHERE callable.oid = helper_oid
        AND namespace.nspname = 'public'
        AND callable.proowner = database_owner_oid
        AND language.lanname = 'sql'
        AND callable.prokind = 'f'
        AND callable.prosecdef
        AND callable.proleakproof = FALSE
        AND callable.proisstrict = FALSE
        AND callable.proretset = FALSE
        AND callable.provolatile = 's'
        AND callable.proparallel = 'u'
        AND callable.procost = 100
        AND callable.prorows = 0
        AND callable.prosupport = 0
        AND callable.provariadic = 0
        AND callable.prorettype = 'pg_catalog.bool'::pg_catalog.regtype
        AND callable.pronargs = 1
        AND callable.pronargdefaults = 0
        AND callable.proargtypes[0] =
            'pg_catalog.text'::pg_catalog.regtype
        AND callable.proallargtypes IS NULL
        AND callable.proargmodes IS NULL
        AND callable.proargnames = ARRAY['boundary_name']::TEXT[]
        AND callable.proargdefaults IS NULL
        AND callable.protrftypes IS NULL
        AND callable.probin IS NULL
        AND callable.prosqlbody IS NULL
        AND callable.proconfig = ARRAY[
          'search_path=pg_catalog, public, pg_temp'
        ]::TEXT[]
        AND pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(
          callable.prosrc, 'UTF8'
        )), 'hex') =
          '4e96e14b9bd337559df5a178a83d76490fa6cba73aed3ced3b2c4a4da644ee01'
    )
    OR EXISTS (
      WITH expected(grantee_oid, grantor_oid, privilege_type, is_grantable) AS (
        VALUES
          (database_owner_oid, database_owner_oid, 'EXECUTE'::TEXT, FALSE),
          ('quillmd_runtime'::pg_catalog.regrole::OID,
            database_owner_oid, 'EXECUTE'::TEXT, FALSE),
          ('quillmd_release_control'::pg_catalog.regrole::OID,
            database_owner_oid, 'EXECUTE'::TEXT, FALSE),
          ('quillmd_release_security'::pg_catalog.regrole::OID,
            database_owner_oid, 'EXECUTE'::TEXT, FALSE),
          ('quillmd_audit_dispatcher'::pg_catalog.regrole::OID,
            database_owner_oid, 'EXECUTE'::TEXT, FALSE),
          ('quillmd_auth_email_dispatcher'::pg_catalog.regrole::OID,
            database_owner_oid, 'EXECUTE'::TEXT, FALSE),
          ('quillmd_backup'::pg_catalog.regrole::OID,
            database_owner_oid, 'EXECUTE'::TEXT, FALSE)
      ), actual AS (
        SELECT acl.grantee, acl.grantor,
          acl.privilege_type::TEXT, acl.is_grantable
        FROM pg_catalog.pg_proc callable
        CROSS JOIN LATERAL pg_catalog.aclexplode(callable.proacl) acl
        WHERE callable.oid = helper_oid
      )
      (SELECT * FROM actual EXCEPT ALL SELECT * FROM expected)
      UNION ALL
      (SELECT * FROM expected EXCEPT ALL SELECT * FROM actual)
    )
    OR EXISTS (
      WITH expected(role_oid, dependency_type) AS (
        VALUES
          ('quillmd_runtime'::pg_catalog.regrole::OID, 'a'::"char"),
          ('quillmd_release_control'::pg_catalog.regrole::OID, 'a'::"char"),
          ('quillmd_release_security'::pg_catalog.regrole::OID, 'a'::"char"),
          ('quillmd_audit_dispatcher'::pg_catalog.regrole::OID, 'a'::"char"),
          ('quillmd_auth_email_dispatcher'::pg_catalog.regrole::OID, 'a'::"char"),
          ('quillmd_backup'::pg_catalog.regrole::OID, 'a'::"char")
      ), actual AS (
        SELECT dependency.refobjid, dependency.deptype
        FROM pg_catalog.pg_shdepend dependency
        WHERE dependency.dbid = (
            SELECT database.oid
            FROM pg_catalog.pg_database database
            WHERE database.datname = pg_catalog.current_database()
          )
          AND dependency.classid =
              'pg_catalog.pg_proc'::pg_catalog.regclass
          AND dependency.objid = helper_oid
          AND dependency.objsubid = 0
          AND dependency.refclassid =
              'pg_catalog.pg_authid'::pg_catalog.regclass
      )
      (SELECT * FROM actual EXCEPT ALL SELECT * FROM expected)
      UNION ALL
      (SELECT * FROM expected EXCEPT ALL SELECT * FROM actual)
    )
  THEN
    RAISE EXCEPTION 'Exact database-principal helper contract is required';
  END IF;
END
$exact_helper_contract$;

COMMIT;
`;
}

try {
  const generated = generate();
  if (process.argv.includes("--write")) {
    writeFileSync(outputPath, generated, "utf8");
    process.stdout.write("EXACT_DATABASE_PRINCIPAL_V9_GENERATE_PASS\n");
  } else {
    assert.equal(readFileSync(outputPath, "utf8"), generated);
    process.stdout.write("EXACT_DATABASE_PRINCIPAL_V9_SYNC_PASS\n");
  }
} catch {
  process.stderr.write("EXACT_DATABASE_PRINCIPAL_V9_GENERATE_FAIL\n");
  process.exitCode = 1;
}
