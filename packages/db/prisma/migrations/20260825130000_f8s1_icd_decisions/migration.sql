-- ===========================================================================
-- F8-S1 — THE ICD DECISION SUBSTRATE.
-- ---------------------------------------------------------------------------
-- F8's build is a DECISION SURFACE over a coding engine that already emits the
-- right shape. Constraints (a) evidence-mandatory and (b) allowlist-validated
-- are satisfied by `07a-icd-coding.ts` today. This file lands the storage for
-- (c) the physician's authority and (d) its audit trail.
--
-- ---------------------------------------------------------------------------
-- 1 · A NEW NULLABLE COLUMN, NOT A KEY INSIDE `icdCodes`
-- ---------------------------------------------------------------------------
-- ⚠️ `worker/layers/07a-icd-coding.ts:570-573` writes
--
--       prisma.transcribeVisit.update({ data: { icdCodes: filtered } })
--
-- which REPLACES the column wholesale — it is not a merge. Anything hung off
-- that blob is whatever the last L7a run says it is, so a `decisions` key
-- there would depend on L7a never running again. A separate column removes the
-- coupling rather than relying on it.
--
-- ⚠️ AND THE REACHABILITY IS STATED HONESTLY, BECAUSE AN EARLIER DRAFT OF THIS
-- COMMENT OVERSTATED IT. It claimed a retry rewrites the column. Measured by
-- reading the shipped writers: `icdCodes` has exactly ONE writer, and
-- `worker/layer-skip.ts:101` skips L7a whenever that column `hasContent` —
-- true for ANY non-null JSON. `POST /api/visits/[id]/retry` re-enqueues
-- without clearing it. So NO shipped path rewrites `icdCodes` under a live
-- decision today; the separation is defensive, and `lib/icd-decisions.ts`
-- enumerates what would re-arm it.
--
-- NULLABLE, deliberately: NULL means "never decided", `{}` means "decided and
-- then cleared". Those are different facts and collapsing them would be the
-- refusal-vs-absence collapse AGENTS.md names. Nothing is backfilled and no
-- write path is owed a sweep — that rule is scoped to NOT NULL columns.
--
-- No index. The column is only ever read by primary key, on the visit row the
-- request already loaded. An index here would be drift with no reader.
--
-- ---------------------------------------------------------------------------
-- 2 · THE THIRD LAYER OF THE AuditAction ENUM
-- ---------------------------------------------------------------------------
-- ⚠️ A new label needs THREE edits, and each layer looks sufficient from the
-- one above it:
--
--   the TypeScript union in `apps/transcribe-md/src/lib/audit.ts` -> `tsc` is
--     happy without this file
--   the Prisma enum in `schema.prisma`                            -> `prisma
--     validate` is happy without this file
--   THIS FILE                                                     -> the enum
--     Postgres actually holds
--
-- That has shipped broken three times in this repo (`535d30d9` on 2026-08-03,
-- and twice on 2026-08-06 — the second passing `prisma validate`, `tsc` and
-- 3192 unit tests). `logAudit` is deliberately fire-and-forget so an audit
-- write can never refuse a clinical action, which means a missing label
-- produces `invalid input value for enum "AuditAction"` in a log nobody reads
-- and nothing anywhere else.
--
-- ⚠️ Postgres has no `ALTER TYPE … DROP VALUE`, so every label added here is
-- permanent and the count is a considered number.
--
-- WHY THREE AND NOT TWO. Accept and Reject are obviously events. CLEARED
-- (Undo) is the third because *"the doctor un-accepted a code"* and *"the
-- doctor never accepted it"* are different clinical facts, and a coding audit
-- that cannot separate them cannot reconstruct what was decided on the record
-- being signed. A NO-OP is not an event and writes nothing — re-asserting the
-- state already stored is refused at the pure layer before any row is written,
-- the same reasoning `PROMO_GRANT_CREDITED` uses for its `already_granted`
-- case.
--
-- NO PHI IN THE METADATA. `{ code, fromState, toState }` — the code alone is
-- non-PHI structured billing data, which `07a-icd-coding.ts:471-473` already
-- states in as many words while deliberately excluding the AI-emitted
-- description from its own rejection row. The same exclusion applies here.
-- ===========================================================================

ALTER TABLE "transcribe_visits" ADD COLUMN IF NOT EXISTS "icdDecisions" JSONB;

ALTER TYPE "AuditAction" ADD VALUE IF NOT EXISTS 'ICD_CODE_ACCEPTED';
ALTER TYPE "AuditAction" ADD VALUE IF NOT EXISTS 'ICD_CODE_REJECTED';
ALTER TYPE "AuditAction" ADD VALUE IF NOT EXISTS 'ICD_CODE_DECISION_CLEARED';
