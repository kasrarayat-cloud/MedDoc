-- sourceType on semantic mappings — where a field's value legitimately comes from.
--
-- 'extraction' fills from a cited EncounterFact. 'manual' is a per-visit human
-- value nobody can know (the technologist on shift): it renders BLANK and is
-- attested rather than blocking certification. 'context_default' and
-- 'visit_metadata' are RESERVED and unimplemented — a deterministic fill puts
-- content into a signed note the clinician never dictated, and the flagged
-- review-before-sign lane for that does not exist yet.
--
-- Without this column the classification was lost on every write→read round
-- trip: mappings came back as 'extraction' and the manual carve-outs in the
-- gate were inert code.
--
-- ADDITIVE: one column, NOT NULL with a DEFAULT, so every existing row is
-- valid immediately and no backfill is needed. No constraint or index changes.
--
-- ROLLBACK: ALTER TABLE "template_twin_semantic_mappings" DROP COLUMN "sourceType";
--   Safe while nothing depends on it; a dropped column simply returns the
--   schema default ('extraction') behaviour that predated this change.
ALTER TABLE "template_twin_semantic_mappings"
  ADD COLUMN "sourceType" TEXT NOT NULL DEFAULT 'extraction';
