-- ===========================================================================
-- FOUNDATION B7 STEP 3c — THE `PROMO_GRANT_CREDITED` AuditAction VALUE.
-- ---------------------------------------------------------------------------
-- Ruling #99 authorized the promo grant in full and required "one audit row per
-- grant". `logAudit` cannot write a label the Postgres enum does not hold, so
-- this file is the half of that requirement the database actually reads.
--
-- ⚠️ THE THIRD LAYER, AND THE ONLY ONE THAT IS CHECKED BY POSTGRES. A new label
-- needs THREE edits, and each layer looks sufficient from the one above it:
--
--   the TypeScript unions in `lib/audit.ts`  → `tsc` is happy without this file
--     (TWO of them — transcribe-md AND meddoc-pro each mirror the enum, and
--      step 3c writes a grant row from BOTH apps, so both unions move)
--   the Prisma enum in `schema.prisma`       → `prisma validate` is happy too
--   THIS FILE                                → the enum Postgres actually holds
--
-- That has shipped broken three times in this repo (`535d30d9` on 2026-08-03,
-- and twice on 2026-08-06 — the second passing `prisma validate`, `tsc` and
-- 3192 unit tests). `gate-audit-enum-migration.test.ts` now compares the schema
-- against this directory, so the omission fails in the unit suite instead of in
-- production. It is still worth stating here: the failure mode is SILENT.
-- `logAudit` is deliberately fire-and-forget so an audit write can never refuse
-- a clinical action, which means a missing label produces
-- `invalid input value for enum "AuditAction"` in a log nobody reads and
-- nothing anywhere else.
--
-- ---------------------------------------------------------------------------
-- WHY ONE LABEL AND NOT TWO
-- ---------------------------------------------------------------------------
-- ⚠️ Postgres has no `ALTER TYPE … DROP VALUE`, so every label added here is
-- permanent and the count is a considered number, not a default.
--
-- A grant has exactly two outcomes: it was written, or the practice already had
-- one (`already_granted`, the global unique on `idempotencyKey` doing its job).
-- Only the FIRST is an event. The second is the ABSENCE of an event — nothing
-- changed, no money moved, and a row saying so would be a write amplification
-- on every re-run of the backfill and on every reactivation of an already-
-- funded practice. B9 reconciles grants against `ledger_entries`, where the
-- authoritative record already lives; the audit row is the actor-and-occasion
-- record for the write that happened.
--
-- Contrast `CHECKOUT_TOPUP_DUPLICATE`, which DOES record its no-op: there the
-- duplicate is a message Stripe SENT US and the fact that they retried is
-- itself the thing an operator asks about. Nobody sends us a grant.
-- ===========================================================================

-- A `grant` row was appended to `ledger_entries` for a practice. Emitted by all
-- three doors — the signup transaction, the one-shot backfill, and the
-- reactivation path — with metadata { practiceId, amountMicroUsd, bucket,
-- balanceAfter, seq, door }, where `balanceAfter` and `seq` are read BACK off
-- the row the derive trigger wrote rather than being the caller's opinion.
--
-- ⚠️ NO PHI, AND NOT EVEN A USER ID BEYOND THE ACTOR. A grant is a fact about a
-- practice's wallet; the doctor's identity is not part of it.
ALTER TYPE "AuditAction" ADD VALUE IF NOT EXISTS 'PROMO_GRANT_CREDITED';
