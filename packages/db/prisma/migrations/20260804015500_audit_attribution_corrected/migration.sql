-- ⚠️ THIS MIGRATION IS THE POINT. `audit_logs.action` is a Postgres ENUM, and
-- `logAudit` is fire-and-forget (`void logAudit({...})`). A label added only to
-- the TypeScript union in lib/audit.ts is REJECTED by the insert and the
-- rejection is DISCARDED — the code appears to work and writes nothing. That
-- exact bug shipped on 2026-08-02 (commit 535d30d9) and is why
-- `gate-audit-action-parity` exists.
--
-- ALTER TYPE ... ADD VALUE is not transactional on older PostgreSQL and cannot
-- be rolled back; IF NOT EXISTS makes it idempotent so a re-run is safe.
ALTER TYPE "AuditAction" ADD VALUE IF NOT EXISTS 'AUDIT_ATTRIBUTION_CORRECTED';
