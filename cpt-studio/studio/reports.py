def _reference_sources(assessment):
    """Installed sources as recorded on the assessment; anything recorded as not connected, then standing gaps."""
    entries = [{key: source.get(key) for key in REFERENCE_KEYS if key in source}
               for source in assessment.reference_sources or []]
    recorded = {entry.get('key'): ' '.join(filter(None, (f'{entry.get("title") or entry.get("key")} —',
                                                          entry.get('license_note'), entry.get('scope_note'))))
                for entry in entries if entry.get('connected') is False}
    standing = [recorded.pop(key, text) for key, text in NOT_CONNECTED]
    return {'connected': [entry for entry in entries if entry.get('connected') is not False],
            'not_connected': standing + list(recorded.values())}


