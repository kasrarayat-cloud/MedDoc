class ReportNotReady(ValueError):
    """A reviewed report was requested before the review is complete."""

    def __init__(self, blockers):
        self.blockers = list(blockers)
        super().__init__('The reviewed report is not available: ' + '; '.join(self.blockers) + '.')


def _ts(value):
    return value.astimezone(dt_timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ') if value else None


def _human(value):
    return str(value).replace('_', ' ')


def _family_label(slug):
    return PROFILES[slug].label if slug in PROFILES else slug


# --- snapshot ----------------------------------------------------------------------

def _root(revision):
    root = revision
    while root.parent_id:
        root = root.parent
    return root


def _source(revision):
    root = _root(revision)
    source = root.source_file
    if source is None:
        return {'kind': 'paste', 'name': None, 'media_type': 'text/plain', 'size': None,
                'sha256': hashlib.sha256(root.pasted_text.encode('utf-8')).hexdigest()}
    return {'kind': 'file', 'name': source.original_name, 'media_type': source.media_type, 'size': source.size,
            'sha256': source.sha256}


def _revision(revision):
    return {
        'id': str(revision.pk), 'number': revision.number, 'kind': revision.kind,
        'parent_number': revision.parent.number if revision.parent_id else None,
        'created_at': _ts(revision.created_at), 'text_sha256': revision.text_sha256,
        'characters': len(revision.text),
        'extraction': {'status': revision.extraction_status, 'method': revision.extraction_method,
                       'pages': len(revision.pages or []), 'ocr_pages': list(revision.ocr_pages or []),
                       'messages': [str(m) for m in revision.messages or []]},
        'source': _source(revision),
    }


def _matches(span, text):
    start, end = span.get('start'), span.get('end')
    return (type(start) is int and type(end) is int and 0 <= start < end <= len(text)
            and text[start:end] == span.get('text'))


def _context(context, text):
    facts = {}
    for name, fact in (context.facts or {}).items():
        facts[name] = {'value': fact.get('value'), 'origin': fact.get('origin'), 'note': fact.get('note') or '',
                       'evidence': [{'start': s['start'], 'end': s['end'], 'text': s['text']}
                                    for s in fact.get('evidence') or () if _matches(s, text)]}
    return {'id': str(context.pk), 'version': context.version, 'facts': facts,
            'user_values': dict(context.user_values or {})}


def _decision(decision):
    """decided_at is when the reviewer decided; a carry is reported separately, never as the decision time."""
    if decision is None:
        return None
    carried = bool(decision.carried_from_id)
    return {'id': str(decision.pk), 'action': decision.action, 'reviewer': decision.reviewer.label(),
            'reviewer_kind': decision.reviewer_kind, 'decided_at': _ts(review.decision_root(decision).created_at),
            'note': decision.note, 'acknowledgement': decision.acknowledgement,
            'carried_from': str(decision.carried_from_id) if carried else None,
            'carried_at': _ts(decision.created_at) if carried else None}


def _list_for(proposal, decision, kind):
    if proposal.bucket == Proposal.ALTERNATIVE:
        return 'alternative'
    action = decision.action if decision else None
    if action == Decision.REJECT:
        return 'rejected'
    if action == Decision.APPROVE and kind == REVIEWED:
        return 'approved'
    if proposal.bucket == Proposal.EXCLUDED and action in (None, Decision.CONFIRM):
        return 'excluded'
    return 'undecided'


def _check(check):
    return {key: str(check.get(key) or '') for key in ('id', 'label', 'status', 'detail', 'source')}


def _reinstated(proposal, decision):
    """An excluded proposal carrying a decision was reinstated, unless that decision confirms the exclusion."""
    return (proposal.bucket == Proposal.EXCLUDED and decision is not None
            and decision.action != Decision.CONFIRM)


def _item(proposal, decision, kind, text):
    exact = review.exact_evidence(proposal.evidence, text)
    return {
        'id': str(proposal.pk), 'key': proposal.key, 'list': _list_for(proposal, decision, kind),
        'bucket': proposal.bucket, 'code': proposal.code, 'code_kind': proposal.code_kind, 'family': proposal.family,
        'family_label': _family_label(proposal.family), 'profile_version': proposal.profile_version,
        'status': proposal.status, 'status_label': review.status_label(proposal.status),
        'exclusion_reason': proposal.exclusion_reason, 'reinstatable': proposal.reinstatable,
        'reinstated': _reinstated(proposal, decision),
        'reinstated_by': _decision(review.reinstatement_for(decision)) if _reinstated(proposal, decision) else None,
        'units': proposal.units, 'rationale': proposal.rationale,
        'evidence': [{'start': s['start'], 'end': s['end'], 'text': s['text'], 'page': s.get('page')} for s in exact],
        'unmatched_evidence': len(proposal.evidence or []) - len(exact),
        'checks': [_check(c) for c in proposal.checks or []],
        'modifier_considerations': [str(m) for m in proposal.modifier_considerations or []],
        'fingerprint': proposal.fingerprint, 'decision': _decision(decision),
    }


def _clarification(question):
    return {'id': str(question.pk), 'scope': question.scope, 'family': question.family, 'fact': question.fact,
            'question': question.question, 'reason': question.reason,
            'code': question.proposal.code if question.proposal_id else None}


def _not_verified(items, assessment):
    return {
        'standing': [{'id': i, 'status': s, 'detail': d} for i, s, d in STANDING_NOT_VERIFIED],
        'checks': [{'code': item['code'], 'list': item['list'], 'id': c['id'], 'label': c['label'],
                    'detail': c['detail']}
                   for item in items for c in item['checks'] if c['status'] == 'not_verified'],
        'encounter_checks': [{'id': c['id'], 'label': c['label'], 'detail': c['detail']}
                             for c in map(_check, assessment.encounter_checks or [])
                             if c['status'] == 'not_verified'],
        'unsupported': [{**{key: str(entry.get(key) or '') for key in ('family', 'label', 'status', 'detail')},
                         'codes': [str(code) for code in entry.get('codes') or []]}
                        for entry in assessment.unsupported or []],
    }


def _reference_sources(assessment):
    """Installed sources as recorded on the assessment; anything recorded as not connected, then standing gaps."""
    entries = [{key: source.get(key) for key in REFERENCE_KEYS if key in source}
               for source in assessment.reference_sources or []]
    recorded = {entry.get('key'): ' '.join(filter(None, (f'{entry.get("title") or entry.get("key")} —',
                                                          entry.get('license_note'), entry.get('scope_note'))))
                for entry in entries if entry.get('connected') is False}
    standing = [recorded.pop(key, text) for key, text in NOT_CONNECTED]
    return {'connected': [entry for entry in entries if entry.get('connected') is not False],
            'not_connected': standing + list(recorded.values())}


def _provider_runs(encounter, assessment):
    return [{
        'id': str(run.pk), 'revision_number': run.revision.number, 'provider': run.provider,
        'mode': 'replay' if run.provider == 'replay' else 'live', 'state': run.state, 'sent': run.sent,
        'http_status': run.http_status, 'usage': run.usage or {}, 'usage_basis': run.usage_basis,
        'request_sha256': run.request_sha256, 'response_sha256': run.response_sha256,
        'reused_from': str(run.reused_from_id) if run.reused_from_id else None,
        'reconciled': run.reconciled_at is not None, 'created_at': _ts(run.created_at),
        'used_by_assessment': run.pk == assessment.provider_run_id,
    } for run in encounter.provider_runs.select_related('revision').order_by('created_at', 'pk')]


def _history(encounter, assessment):
    decisions = list(encounter.decisions.select_related('proposal', 'reviewer', 'revision', 'invalidation',
                                                        'invalidation__by_revision').order_by('sequence'))
    carried = {d.carried_from_id for d in decisions if d.carried_from_id}
    history = []
    for decision in decisions:
        invalidation = getattr(decision, 'invalidation', None)
        history.append({
            'id': str(decision.pk), 'recorded_at': _ts(decision.created_at), 'code': decision.proposal.code,
            'action': decision.action, 'reviewer': decision.reviewer.label(), 'reviewer_kind': decision.reviewer_kind,
            'revision_number': decision.revision.number, 'assessment_id': str(decision.assessment_id),
            'current_assessment': decision.assessment_id == assessment.pk,
            'carried_from': str(decision.carried_from_id) if decision.carried_from_id else None,
            'carried_forward': decision.pk in carried,
            'invalidated': None if invalidation is None else {
                'reason': invalidation.reason, 'at': _ts(invalidation.created_at),
                'by_revision_number': invalidation.by_revision.number if invalidation.by_revision_id else None,
                'by_context_id': str(invalidation.by_context_id) if invalidation.by_context_id else None},
        })
    return history


def snapshot(encounter, kind):
    """Everything a report shows, read from persisted rows. A reviewed snapshot needs a complete review."""
    if kind not in KINDS:
        raise ValueError('Choose a draft or reviewed report.')
    encounter = Encounter.objects.select_related('workspace__category').get(pk=encounter.pk)
    assessment = review.live_assessment(encounter)
    if assessment is None:
        raise ValueError('There is no assessment of the current revision to report yet.')
    ready = review.readiness(encounter)
    if kind == REVIEWED and not ready['reviewed']:
        raise ReportNotReady(ready['blockers'])
    revision = assessment.revision
    current = review.current_decisions(assessment)
    questions = list(assessment.clarifications.filter(state=Clarification.OPEN).select_related('proposal')
                     .order_by('created_at', 'pk'))
    items = [_item(p, current.get(p.pk), kind, revision.text) for p in assessment.proposals.order_by('position')]
    if kind == REVIEWED and any(item['list'] == 'undecided' for item in items):
        raise ReportNotReady(['A proposed code has no approve or reject decision'])
    workspace = encounter.workspace
    return {
        'format_version': FORMAT_VERSION, 'kind': kind, 'generated_at': _ts(timezone.now()),
        'synthetic': SYNTHETIC_LINE,
        'agent_review': any(entry['reviewer_kind'] == 'agent' for item in items
                            for entry in (item['decision'], item['reinstated_by']) if entry),
        'encounter': {'id': str(encounter.pk), 'title': encounter.title,
                      'workspace': {'id': str(workspace.pk), 'name': workspace.name},
                      'category': {'slug': workspace.category.slug, 'name': workspace.category.name}},
        'revision': _revision(revision),
        'context': _context(assessment.context, revision.text),
        'assessment': {'id': str(assessment.pk), 'created_at': _ts(assessment.created_at),
                       'sha256': assessment.sha256, 'profiles_version': assessment.profiles_version,
                       'engine_version': assessment.engine_version, 'routing_version': assessment.routing.version,
                       'routing_sha256': assessment.routing.sha256,
                       'encounter_checks': [_check(c) for c in assessment.encounter_checks or []]},
        'readiness': ready,
        'proposals': items,
        'clarifications': [_clarification(q) for q in questions],
        'not_verified': _not_verified(items, assessment),
        'provider_runs': _provider_runs(encounter, assessment),
        'reference_sources': _reference_sources(assessment),
        'decision_history': _history(encounter, assessment),
    }


def snapshot_digest(snap):
    """sha256 of the snapshot without its generation time: equal persisted state, equal digest."""
    return sha256_json({key: value for key, value in snap.items() if key != 'generated_at'})


