def _root(revision):
    root = revision
    while root.parent_id:
        root = root.parent
    return root


def _source(revision):
    root = _root(revision)
    source = root.source_file
    if source is None:
        return {'kind': 'paste', 'name': None, 'media_type': 'text/plain', 'size': None,
                'sha256': hashlib.sha256(root.pasted_text.encode('utf-8')).hexdigest()}
    return {'kind': 'file', 'name': source.original_name, 'media_type': source.media_type, 'size': source.size,
            'sha256': source.sha256}


def _revision(revision):
    return {
        'id': str(revision.pk), 'number': revision.number, 'kind': revision.kind,
        'parent_number': revision.parent.number if revision.parent_id else None,
        'created_at': _ts(revision.created_at), 'text_sha256': revision.text_sha256,
        'characters': len(revision.text),
        'extraction': {'status': revision.extraction_status, 'method': revision.extraction_method,
                       'pages': len(revision.pages or []), 'ocr_pages': list(revision.ocr_pages or []),
                       'messages': [str(m) for m in revision.messages or []]},
        'source': _source(revision),
    }


def _matches(span, text):
    start, end = span.get('start'), span.get('end')
    return (type(start) is int and type(end) is int and 0 <= start < end <= len(text)
            and text[start:end] == span.get('text'))


def _context(context, text):
    facts = {}
    for name, fact in (context.facts or {}).items():
        facts[name] = {'value': fact.get('value'), 'origin': fact.get('origin'), 'note': fact.get('note') or '',
                       'evidence': [{'start': s['start'], 'end': s['end'], 'text': s['text']}
                                    for s in fact.get('evidence') or () if _matches(s, text)]}
    return {'id': str(context.pk), 'version': context.version, 'facts': facts,
            'user_values': dict(context.user_values or {})}


def _decision(decision):
    """decided_at is when the reviewer decided; a carry is reported separately, never as the decision time."""
    if decision is None:
        return None
    carried = bool(decision.carried_from_id)
    return {'id': str(decision.pk), 'action': decision.action, 'reviewer': decision.reviewer.label(),
            'reviewer_kind': decision.reviewer_kind, 'decided_at': _ts(review.decision_root(decision).created_at),
            'note': decision.note, 'acknowledgement': decision.acknowledgement,
            'carried_from': str(decision.carried_from_id) if carried else None,
            'carried_at': _ts(decision.created_at) if carried else None}


def _list_for(proposal, decision, kind):
    if proposal.bucket == Proposal.ALTERNATIVE:
        return 'alternative'
    action = decision.action if decision else None
    if action == Decision.REJECT:
        return 'rejected'
    if action == Decision.APPROVE and kind == REVIEWED:
        return 'approved'
    if proposal.bucket == Proposal.EXCLUDED and action in (None, Decision.CONFIRM):
        return 'excluded'
    return 'undecided'


def _check(check):
    return {key: str(check.get(key) or '') for key in ('id', 'label', 'status', 'detail', 'source')}


def _reinstated(proposal, decision):
    """An excluded proposal carrying a decision was reinstated, unless that decision confirms the exclusion."""
    return (proposal.bucket == Proposal.EXCLUDED and decision is not None
            and decision.action != Decision.CONFIRM)


