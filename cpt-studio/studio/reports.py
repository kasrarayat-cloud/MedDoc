def _indent(text, prefix):
    """Stored text on a report line: a line break in any form (CR, CRLF, LF, U+2028 ...) continues at prefix."""
    return ('\n' + prefix).join(str(text).splitlines() or [''])


def _evidence_line(span):
    page = f', page {span["page"]}' if span.get('page') else ''
    return f'"{span["text"]}" [chars {span["start"]}–{span["end"]}{page}]'


def _who(reviewer, kind):
    """The reviewer's label with the kind recorded on the decision; an agent always reads as an automated agent."""
    if kind == 'agent':
        return reviewer if 'automated agent' in reviewer else f'{reviewer} (automated agent)'
    return f'{reviewer} ({kind})'


def _decision_words(decision):
    verb = {'approve': 'approved', 'reject': 'rejected', 'reinstate': 'reinstated for review',
            'confirm': 'exclusion confirmed'}[decision['action']]
    carried = (f' (carried from an earlier assessment of this revision at {decision["carried_at"]})'
               if decision['carried_from'] else '')
    return f'{verb} by {_who(decision["reviewer"], decision["reviewer_kind"])} at {decision["decided_at"]}{carried}'


def _decision_lines(item, kind):
    decision, pad = item['decision'], '     '
    if decision is None:
        return [f'{pad}Current decision: none']
    if kind == REVIEWED:
        lines = [f'{pad}Decision: {_decision_words(decision)}']
    elif decision['action'] == Decision.APPROVE:
        lines = [f'{pad}Current decision: {_decision_words(decision)} — provisional; this draft is not a '
                 'reviewed report']
    else:
        lines = [f'{pad}Current decision: {_decision_words(decision)}']
    if decision['acknowledgement']:
        lines.append(f'{pad}Acknowledgement: {_indent(decision["acknowledgement"], pad + "  ")}')
    if decision['note']:
        lines.append(f'{pad}Note: {_indent(decision["note"], pad + "  ")}')
    return lines


def _item_block(number, item, kind):
    pad = '     '
    lines = [f'  {number}. {item["code"]} · {item["family_label"]} · units {item["units"]}',
             f'{pad}{DESCRIPTOR_LINE}', f'{pad}Profile: {item["profile_version"]}']
    if kind == DRAFT:
        lines.append(f'{pad}Status: ' + ('Reinstated by a reviewer' if item['reinstated'] else item['status_label']))
    if item['reinstated']:
        reason = item['exclusion_reason'] or 'no reason recorded'
        by = item['reinstated_by']
        who = f'by {_who(by["reviewer"], by["reviewer_kind"])} at {by["decided_at"]}' if by else 'by a reviewer'
        lines.append(f'{pad}Reinstated from exclusion {who}: {_indent(reason, pad + "  ")}')
    lines += _decision_lines(item, kind)
    lines.append(f'{pad}Evidence:')
    lines += [f'{pad}  - {_indent(_evidence_line(span), pad + "    ")}' for span in item['evidence']] or [
        f'{pad}  - none matches the revision text exactly']
    if item['unmatched_evidence']:
        lines.append(f'{pad}  ({item["unmatched_evidence"]} cited passage(s) did not match the revision text '
                     'exactly and are not shown)')
    if item['rationale']:
        lines.append(f'{pad}Rationale: {_indent(item["rationale"], pad + "  ")}')
    if item['modifier_considerations']:
        lines.append(f'{pad}Modifier considerations (none assigned): ' + '; '.join(item['modifier_considerations']))
    return lines


def _source_section(snap):
    enc, rev, source, assessment = snap['encounter'], snap['revision'], snap['revision']['source'], snap['assessment']
    kind = {'upload': 'uploaded file', 'paste': 'pasted text', 'addendum': 'addendum'}.get(rev['kind'], rev['kind'])
    if rev['parent_number']:
        kind += f' to revision {rev["parent_number"]}'
    lines = [f'  Encounter: {enc["title"]}', f'  Encounter id: {enc["id"]}',
             f'  Workspace: {enc["workspace"]["name"]} (category {enc["category"]["name"]})',
             f'  Revision: {rev["number"]} ({kind}), recorded {rev["created_at"]}']
    if source['kind'] == 'file':
        lines.append(f'  Source file: {source["name"]} · {source["media_type"]} · {source["size"]} bytes · '
                     f'sha256 {source["sha256"]}')
    else:
        lines.append(f'  Source: pasted text (no original file) · sha256 of the text as submitted {source["sha256"]}')
    extraction = rev['extraction']
    lines += [f'  Extracted text: {rev["characters"]} characters · sha256 {rev["text_sha256"]}',
              f'  Extraction: {extraction["status"]} ({extraction["method"]}) · {extraction["pages"]} page(s)']
    if extraction['ocr_pages']:
        lines.append('  OCR pages: ' + ', '.join(str(page) for page in extraction['ocr_pages']))
    lines += [f'  Extraction message: {message}' for message in extraction['messages']]
    lines += [f'  Assessment: {assessment["id"]} · recorded {assessment["created_at"]} · sha256 {assessment["sha256"]}',
              f'  Versions: profiles {assessment["profiles_version"]} · engine {assessment["engine_version"]} · '
              f'routing {assessment["routing_version"]}']
    return lines


def _context_section(snap):
    facts = snap['context']['facts']
    names = [name for name in CONTEXT_FACTS if name in facts] + sorted(set(facts) - set(CONTEXT_FACTS))
    lines = []
    for name in names:
        fact = facts[name]
        origin = fact['origin']
        value = fact['value'] if fact['value'] and origin in ('document', 'user') else None
        wording = ORIGIN_WORDING.get(origin, f'origin {origin}')
        line = f'  {_human(name).capitalize()}: ' + (f'{_human(value)} ({wording})' if value else wording)
        if fact['note']:
            line += f' — {fact["note"]}'
        lines.append(line)
        lines += [f'    Evidence: {_evidence_line(span)}' for span in fact['evidence']]
    return lines or ['  No context facts were recorded.']


def _short_line(item):
    return f'  - {item["code"]} · {item["family_label"]}'


def _rejected_section(snap):
    lines = []
    for item in snap['proposals']:
        if item['list'] == 'rejected':
            lines.append(f'{_short_line(item)} — {_decision_words(item["decision"])}')
            if item['decision']['note']:
                lines.append(f'     Note: {_indent(item["decision"]["note"], "       ")}')
    return lines or ['  None.']


def _numbered(snap, wanted, kind):
    lines = []
    for number, item in enumerate((i for i in snap['proposals'] if i['list'] == wanted), start=1):
        lines += _item_block(number, item, kind)
    return lines or ['  None.']


def _excluded_section(snap):
    lines = []
    for item in snap['proposals']:
        if item['list'] == 'excluded':
            decision = item['decision']
            if decision is not None:  # only a confirmation leaves an item in this list
                hint = f'. Decision: {_decision_words(decision)}'
            else:
                hint = (' (a reviewer may reinstate it; no reviewer has confirmed this exclusion)'
                        if item['reinstatable'] else '')
            lines.append(f'{_short_line(item)} · {item["code_kind"]} — Excluded: '
                         f'{item["exclusion_reason"] or "no reason recorded"}{hint}')
            if decision is not None and decision['note']:
                lines.append(f'     Note: {_indent(decision["note"], "       ")}')
    return lines or ['  None.']


def _alternatives_section(snap):
    lines = [f'{_short_line(item)} — provider alternative, never selectable'
             + (f': {item["exclusion_reason"]}' if item['exclusion_reason'] else '')
             for item in snap['proposals'] if item['list'] == 'alternative']
    return lines or ['  None.']


def _checks_section(snap):
    lines = []
    for item in snap['proposals']:
        if item['checks']:
            lines.append(f'  {item["code"]} ({item["list"]})')
            lines += [_check_line(check) for check in item['checks']]
    encounter_checks = snap['assessment']['encounter_checks']
    if encounter_checks:
        lines.append('  Encounter')
        lines += [_check_line(check) for check in encounter_checks]
    return lines or ['  No checks were recorded.']


def _check_line(check):
    source = f' · {check["source"]}' if check['source'] else ''
    return f'    [{check["status"].upper()}] {check["id"]} — {check["label"]}: {check["detail"]}{source}'


def _clarifications_section(snap):
    lines = []
    for question in snap['clarifications']:
        subject = question['code'] or ('Encounter' if question['scope'] == 'encounter' else
                                       _family_label(question['family']) or question['scope'])
        lines.append(f'  - {subject} · {_human(question["fact"])} — {question["question"]} ({question["reason"]})')
    return lines or ['  None.']


def _not_verified_section(snap):
    data = snap['not_verified']
    lines = ['  Standing limitations (every code):']
    lines += [f'    - {entry["detail"]}' for entry in data['standing']]
    if data['checks']:
        lines.append('  Per code:')
        lines += [f'    - {c["code"]} ({c["list"]}) · {c["id"]} — {c["label"]}: {c["detail"]}' for c in data['checks']]
    if data['encounter_checks']:
        lines.append('  Encounter:')
        lines += [f'    - {c["id"]} — {c["label"]}: {c["detail"]}' for c in data['encounter_checks']]
    if data['unsupported']:
        lines.append('  Services without a supported GI profile:')
        lines += [f'    - {u["label"] or u["family"]} ({u["status"]}): {u["detail"]}'
                  + (f' Codes: {", ".join(u["codes"])}.' if u['codes'] else '') for u in data['unsupported']]
    return lines


def _provider_section(snap):
    lines = []
    # A succeeded run whose provider check failed was refused whole: the assessment read none of its codes, so it is
    # never "used by this assessment" (round 7 bypass:1).
    refused = any(check['id'] == 'provider.status' and check['status'] == 'fail'
                  for check in snap['assessment']['encounter_checks'])
    for run in snap['provider_runs']:
        mode = 'REPLAY (recorded response, not live output)' if run['mode'] == 'replay' else run['mode']
        status = f' · HTTP {run["http_status"]}' if run['http_status'] else ''
        used = ''
        if run['used_by_assessment']:
            used = (' · read by this assessment; its response was not used'
                    if refused and run['state'] == 'succeeded' else ' · used by this assessment')
        lines.append(f'  - {run["provider"]} · {mode} · {run["state"]}{status} · revision {run["revision_number"]}'
                     f' · requested {run["created_at"]}{used}')
        usage = json.dumps(run['usage'], sort_keys=True, ensure_ascii=False) if run['usage'] else 'none reported'
        lines.append(f'    Usage: {usage}' + (f' ({run["usage_basis"]})' if run['usage_basis'] else ''))
        lines.append(f'    Request sha256: {run["request_sha256"] or "none"} · '
                     f'Response sha256: {run["response_sha256"] or "none"}')
        if run['reused_from']:
            lines.append(f'    Reused retained result {run["reused_from"]}; no new request was sent.')
        if run['reconciled']:
            lines.append('    Unknown outcome reconciled by a workspace member.')
    return lines or ['  No provider request was made.']


def _reference_section(snap):
    connected = snap['reference_sources']['connected']
    lines = ['  Connected:']
    for source in connected:
        applies = source.get('applies')
        applies_text = {True: 'yes', False: 'no'}.get(applies, 'not stated')
        lines.append(f'    - {source.get("key", "")} · {source.get("title", "")} · release {source.get("release", "")}'
                     f' · effective {source.get("effective_start", "")} to {source.get("effective_end", "")}'
                     f' · applies to the service date: {applies_text}'
                     + (f' · {source["note"]}' if source.get('note') else ''))
    if not connected:
        lines.append('    None.')
    lines.append('  Not connected:')
    lines += [f'    - {entry}' for entry in snap['reference_sources']['not_connected']]
    return lines


def _audit_section(snap):
    lines = []
    for entry in snap['decision_history']:
        flags = ['this assessment' if entry['current_assessment'] else f'assessment {entry["assessment_id"]}']
        if entry['carried_from']:
            flags.append(f'carried from {entry["carried_from"]}')
        if entry['carried_forward']:
            flags.append('carried forward to a later assessment')
        lines.append(f'  - {entry["recorded_at"]} · {entry["code"]} · {entry["action"]} · '
                     f'{_who(entry["reviewer"], entry["reviewer_kind"])} · revision {entry["revision_number"]} · '
                     + ' · '.join(flags))
        if entry['invalidated']:
            lines.append(f'      Invalidated {entry["invalidated"]["at"]}: {entry["invalidated"]["reason"]}')
    return lines or ['  No review decisions have been recorded.']


def _review_status(snap):
    ready = snap['readiness']
    if snap['kind'] == REVIEWED:
        return [_reviewed_status_line(snap['proposals'])]
    if ready['reviewed']:
        return ['Review status: complete — a reviewed report is available; this file is a draft.']
    return ['Review status: not complete'] + [f'  - {blocker}' for blocker in ready['blockers']]


def _reviewed_status_line(items):
    """The completed review, counted from the snapshot's own lists: a review that recorded only confirmations says
    so, rather than claiming approve or reject decisions it does not have (round 5, bypass:3)."""
    approved = sum(1 for item in items if item['list'] == 'approved')
    rejected = sum(1 for item in items if item['list'] == 'rejected')
    confirmed = sum(1 for item in items if item['list'] == 'excluded' and item['decision'] is not None)
    return (f'Review status: complete — {approved} approved, {rejected} rejected, {confirmed} documentation-check '
            'exclusion' + ('' if confirmed == 1 else 's') + ' confirmed; every selected or reinstated code has an '
            'approve or reject decision, and every documentation-check exclusion is confirmed or reinstated.')


def _join(lines):
    """Join report lines so that a line break inside any value never starts a line at column 0 or leaves a
    blank line: stored text (a note, a title) cannot forge a section heading or a section boundary."""
    out = []
    for line in lines:
        first, *rest = (_visible(part) for part in (str(line).splitlines() or ['']))
        out.append(first)
        out += [part if part.startswith(CONTINUATION) else CONTINUATION + part for part in rest]
    return '\n'.join(out)


# Control characters a terminal or printer would interpret (ESC sequences can move the cursor and redraw a line,
# backspace and DEL erase): shown escaped, so no rendering of the file shows a line the report does not contain.
CONTROL = re.compile('[\x00-\x08\x0e-\x1f\x7f-\x9f]')


def _visible(part):
    return CONTROL.sub(lambda m: f'\\x{ord(m.group()):02x}', part)


def render_txt(snap) -> bytes:
    kind = snap['kind']
    lines = [HEADLINES[kind], SYNTHETIC_LINE]
    if snap['agent_review']:
        lines.append(AGENT_LINE)
    lines += [f'Generated: {snap["generated_at"]} · format {snap["format_version"]}', *_review_status(snap)]
    sections = [('ENCOUNTER, SOURCE AND REVISION', _source_section(snap)),
                ('ENCOUNTER CONTEXT', _context_section(snap))]
    if kind == REVIEWED:
        sections.append(('APPROVED SELECTIONS', _numbered(snap, 'approved', kind)))
    sections.append(('REJECTED — EXCLUDED FROM APPROVED RESULTS', _rejected_section(snap)))
    if kind == DRAFT:
        # round 7 bypass:4: after a complete review the draft's list holds provisional approvals, not an incomplete
        # review; the 'UNDECIDED' prefix stays (ops/verify_downloads.py finds the section by it)
        title = ('UNDECIDED OR PROVISIONAL — THE REVIEWED REPORT IS AVAILABLE' if snap['readiness'].get('reviewed')
                 else 'UNDECIDED — REVIEW NOT COMPLETE')
        sections.append((title, _numbered(snap, 'undecided', kind)))
    sections += [('EXCLUDED CANDIDATES', _excluded_section(snap)),
                 ('ALTERNATIVES — PROVIDER CANDIDATES, NEVER SELECTED', _alternatives_section(snap)),
                 ('CHECKS', _checks_section(snap)),
                 ('OPEN CLARIFICATIONS', _clarifications_section(snap)),
                 ('NOT VERIFIED', _not_verified_section(snap)),
                 ('PROVIDER USAGE', _provider_section(snap)),
                 ('REFERENCE SOURCES', _reference_section(snap)),
                 ('AUDIT — DECISION HISTORY', _audit_section(snap))]
    for title, body in sections:
        lines += ['', title, *body]
    return (_join(lines) + f'\n\n{SYNTHETIC_LINE}\n').encode('utf-8')


# --- CSV -----------------------------------------------------------------------------

def neutralise(value):
    """A cell a spreadsheet will show as text: formula-leading characters get an apostrophe prefix."""
    text = '' if value is None else str(value)
    return "'" + text if text.startswith(FORMULA_PREFIXES) else text


def _not_verified_cell(item):
    entries = [(entry_id, status) for entry_id, status, _ in STANDING_NOT_VERIFIED]
    seen = {entry_id for entry_id, _ in entries}
    entries += [(c['id'], c['status']) for c in item['checks'] if c['status'] == 'not_verified' and c['id'] not in seen]
    return ';'.join(f'{entry_id}={status}' for entry_id, status in entries)


def _identity_cells(snap):
    return {'report_kind': snap['kind'], 'encounter_id': snap['encounter']['id'],
            'revision_number': snap['revision']['number'], 'source_sha256': snap['revision']['source']['sha256'],
            'text_sha256': snap['revision']['text_sha256'], 'assessment_id': snap['assessment']['id'],
            'synthetic': SYNTHETIC_CELL}


def _csv_row(snap, item):
    decision = item['decision'] or {}
    evidence = ' | '.join(f'"{s["text"]}" [{s["start"]}-{s["end"]}' + (f', p{s["page"]}]' if s.get('page') else ']')
                          for s in item['evidence'])
    row = {**_identity_cells(snap), 'proposal_id': item['id'], 'item_list': item['list'], 'code': item['code'],
           'code_kind': item['code_kind'], 'family': item['family'], 'family_label': item['family_label'],
           'status': item['status'], 'decision': decision.get('action', ''), 'reviewer': decision.get('reviewer', ''),
           'reviewer_kind': decision.get('reviewer_kind', ''), 'decided_at': decision.get('decided_at', ''),
           'decision_carried_from': decision.get('carried_from') or '',
           'decision_carried_at': decision.get('carried_at') or '', 'units': item['units'], 'evidence': evidence,
           'checks': ';'.join(f'{c["id"]}={c["status"]}' for c in item['checks']),
           'not_verified': _not_verified_cell(item), 'modifier_considerations': ' | '.join(item['modifier_considerations']),
           'exclusion_reason': item['exclusion_reason']}
    return [row[column] for column in CSV_COLUMNS]


def _placeholder_row(snap):
    """A report with no proposals still says, in the file, what it is: its kind, its identity and SYNTHETIC."""
    row = {**dict.fromkeys(CSV_COLUMNS, ''), **_identity_cells(snap), 'item_list': 'none',
           'not_verified': _not_verified_cell({'checks': []})}
    return [row[column] for column in CSV_COLUMNS]


def render_csv(snap) -> bytes:
    """RFC 4180: every field quoted, quotes doubled, CRLF records, UTF-8 without a BOM."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, quoting=csv.QUOTE_ALL, lineterminator='\r\n')
    writer.writerow([neutralise(column) for column in CSV_COLUMNS])
    order = {name: index for index, name in enumerate(LISTS)}
    rows = [_csv_row(snap, item) for item in sorted(snap['proposals'], key=lambda i: order[i['list']])]
    for row in rows or [_placeholder_row(snap)]:
        # Control characters are shown escaped here too (round 3, review3:5): a cited passage carrying ESC/CSI,
        # backspace or DEL must not redraw a row when the file is printed in a terminal.
        writer.writerow([neutralise(_visible(cell) if isinstance(cell, str) else cell) for cell in row])
    return buffer.getvalue().encode('utf-8')


RENDERERS = {'txt': render_txt, 'csv': render_csv}


# --- persistence ---------------------------------------------------------------------

def _filename(snap, fmt):
    stamp = snap['generated_at'].replace('-', '').replace(':', '').rstrip('Z')
    return f'CPT-Studio-{snap["kind"]}-{snap["encounter"]["id"][:8]}-r{snap["revision"]["number"]}-{stamp}.{fmt}'


def generate(encounter, kind, fmt, user):
    """Snapshot -> render -> store the bytes once (immutable) with their sha256 and the snapshot digest."""
    if fmt not in RENDERERS:
        raise ValueError('Choose a TXT or CSV report.')
    if kind not in KINDS:
        raise ValueError('Choose a draft or reviewed report.')
    if not (user.is_active and Membership.objects.filter(user=user, workspace_id=encounter.workspace_id,
                                                         active=True).exists()):
        raise PermissionDenied('Only an active member of this workspace can generate its reports.')
    with transaction.atomic():
        locked = Encounter.objects.select_for_update().get(pk=encounter.pk)
        snap = snapshot(locked, kind)
        content = RENDERERS[fmt](snap)
        artifact = ReportArtifact.objects.create(
            encounter=locked, assessment_id=snap['assessment']['id'], kind=kind, fmt=fmt,
            filename=_filename(snap, fmt), content=content, sha256=hashlib.sha256(content).hexdigest(),
            snapshot_sha256=snapshot_digest(snap), generated_by=user)
        audit.record(locked.workspace, 'report.generated', encounter=locked, actor=user, report=str(artifact.pk),
                     assessment=snap['assessment']['id'], kind=kind, fmt=fmt)
    return artifact
