# ═══ 4. Examination grid (D10-like) ═══════════════════════════════════════════════════════════════════════
TWO = (4320, 5760)
THREE = (4320, 5760, 7200)


def f4_exam_grid() -> bytes:
    b = Builder("Vascular and skin examination")
    b.para("Vascular and skin examination", style="Heading 1")                        # b/p[0]
    g = b.table(4, 3)                                                                 # b/tbl[0] pulse grid
    for c, header in enumerate(("Pulse", "Left", "Right")):
        g.cell(0, c).text = header
    for r, pulse in enumerate(("Radial", "Femoral", "Dorsalis pedis"), 1):
        g.cell(r, 0).text = pulse                                                     # tc[1], tc[2] stay empty
    b.para()                                                                          # b/p[1] spacer
    t = b.table(6, 1)                                                                 # b/tbl[1] one column

    def summary(cell, title):
        cell.paragraphs[0].add_run(title)                                             # p[0] title
        b.coded_header(cell.add_paragraph(), ("Normal", "Abnormal", "Not examined"), THREE)   # p[1]
        b.coded_row(cell.add_paragraph(), "", 3, THREE)                                # p[2] unlabelled row

    def comment(cell, title):
        cell.paragraphs[0].add_run(title)                                             # p[0] section title
        cell.add_paragraph("Describe any abnormality")                                # p[1] printed instruction
        cell.add_paragraph("_" * 60)                                                  # p[2] answer line

    summary(t.cell(0, 0), "Pulse summary")                                            # tr[0]
    comment(t.cell(1, 0), "Pulse findings")                                           # tr[1]
    skin = t.cell(2, 0)                                                               # tr[2]
    skin.paragraphs[0].add_run("Skin and nails")                                      # p[0]
    skin.add_paragraph()                                                              # p[1] spacer
    b.coded_header(skin.add_paragraph(), ("Normal", "Abnormal"), TWO)                 # p[2]
    for label in ("Skin colour", "Nail beds", "Capillary refill"):                    # p[3..5]
        b.coded_row(skin.add_paragraph(), label, 2, TWO)
    swelling = t.cell(3, 0)                                                           # tr[3]
    swelling.paragraphs[0].add_run("Lower-limb swelling")                             # p[0]
    swelling.add_paragraph()                                                          # p[1] spacer
    b.coded_header(swelling.add_paragraph(), ("None", "Pitting", "Non-pitting"), THREE)   # p[2]
    for label in ("Ankle", "Mid-calf"):                                               # p[3..4]
        b.coded_row(swelling.add_paragraph(), label, 3, THREE)
    summary(t.cell(4, 0), "Skin and limb summary")                                    # tr[4]
    comment(t.cell(5, 0), "Skin and limb findings")                                   # tr[5]
    b.para()                                                                          # b/p[2] trailing
    return b.bytes()


