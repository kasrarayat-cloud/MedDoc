def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="build twice in memory, compare, write nothing")
    args = ap.parse_args(argv)
    if args.check:
        bad = [name for name, make in FORMS.items() if make() != make()]
        for name in FORMS:
            print(("NOT DETERMINISTIC " if name in bad else "deterministic ") + name)
        return 1 if bad else 0
    args.out.mkdir(parents=True, exist_ok=True)
    lines = []
    for name, make in FORMS.items():
        data = make()
        path = args.out / (name + ".docx")
        path.write_bytes(data)
        if path.read_bytes() != data:
            print("write did not read back: %s" % path, file=sys.stderr)
            return 1
        digest = hashlib.sha256(data).hexdigest()
        lines.append("%s  %s.docx" % (digest, name))
        print("%s  %s.docx  (%d bytes)" % (digest, name, len(data)))
    (args.out / "SHA256SUMS").write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
