// ============================================================================
// Provision (or reset) the synthetic prod-smoke doctor. IDEMPOTENT.
// ----------------------------------------------------------------------------
//   DATABASE_URL=... npx tsx scripts/prod-smoke/provision.ts
//
// Deliberately NOT guarded by assertNonProdDatabase() — this fixture only has a
// point on production. The guard here is scope, not target: it creates exactly
// one practice and one user, both matched on the constants in smoke-account.ts,
// and touches nothing else. See that file for the full safety rationale.
//
// Re-running is safe and is the supported way to rotate the password or undo an
// accidental lockout (failedLoginCount / lockedUntil are cleared every run).
// ============================================================================

import { randomBytes } from 'node:crypto';
import { chmodSync, writeFileSync } from 'node:fs';

import { prisma } from '@meddoc/db';
import bcrypt from 'bcryptjs';

import {
  SMOKE_EMAIL,
  SMOKE_ENV_PATH,
  SMOKE_NAME,
  SMOKE_PRACTICE_NAME,
  SMOKE_PRACTICE_SLUG,
  assertIsSmokeFixture,
} from './smoke-account';

async function main() {
  // An operator-supplied password keeps a known credential across rotations;
  // otherwise mint a fresh 32-char one.
  const password =
    process.env.SMOKE_ACCOUNT_PASSWORD?.trim() || randomBytes(24).toString('base64url');

  // ⚠️ ADMIN-6a — THIS UPSERT NO LONGER WRITES `isActive`, AND THAT IS THE FIX.
  // It used to set `isActive: true` on every run, which was harmless while the
  // flag was a marker nobody read. Now three doors read it, so that line would
  // be a SILENT UN-ARCHIVE — a restore with no audit row, performed by a script
  // outside the one audited verb (`updatePractice`). The create branch takes
  // the column default (true); an archived smoke practice stays archived and
  // this script REFUSES below, naming the audited door to restore it through.
  const practice = await prisma.practice.upsert({
    where: { slug: SMOKE_PRACTICE_SLUG },
    update: { name: SMOKE_PRACTICE_NAME },
    create: { name: SMOKE_PRACTICE_NAME, slug: SMOKE_PRACTICE_SLUG },
  });
  assertIsSmokeFixture(practice);
  if (!practice.isActive) {
    throw new Error(
      'prod-smoke: the smoke practice is ARCHIVED (practices.isActive = false), so its ' +
        'member cannot sign in. Restore it through the audited verb — ' +
        'PATCH /api/admin/practices/<id> {"isActive": true} as a platform administrator — ' +
        'not by writing the flag from a script.',
    );
  }

  const passwordHash = await bcrypt.hash(password, 12);

  const user = await prisma.user.upsert({
    where: { email: SMOKE_EMAIL },
    update: {
      passwordHash,
      // Pre-verified, permanently. This is the whole reason the fixture exists:
      // prod auto-confirm is gated off, so a smoke account can never verify
      // itself through the normal email flow.
      emailVerified: new Date(),
      isActive: true,
      // Clear every state that could refuse a login, so a smoke run never fails
      // for a reason unrelated to what it is testing.
      suspendedAt: null,
      softDeletedAt: null,
      lockedUntil: null,
      failedLoginCount: 0,
      mfaEnabled: false,
      // TRANSCRIBE_MD only — never SUPER_ADMIN. A smoke account must not be
      // able to reach /admin.
      products: ['TRANSCRIBE_MD'],
    },
    create: {
      email: SMOKE_EMAIL,
      name: SMOKE_NAME,
      passwordHash,
      emailVerified: new Date(),
      role: 'DOCTOR',
      products: ['TRANSCRIBE_MD'],
      specialty: 'Vascular Surgery',
      clinicName: SMOKE_PRACTICE_NAME,
      practiceId: practice.id,
      practiceRole: 'OWNER', // T6: the CHECK requires a role for an active member
      isActive: true,
    },
  });
  assertIsSmokeFixture(user);

  if (user.practiceId !== practice.id) {
    throw new Error('prod-smoke: existing smoke user is attached to a different practice.');
  }

  writeFileSync(
    SMOKE_ENV_PATH,
    [
      '# QuillMD synthetic prod-smoke account — generated by scripts/prod-smoke/provision.ts',
      '# NOT a real clinician. Safe to rotate at any time by re-running provision.',
      `SMOKE_EMAIL=${SMOKE_EMAIL}`,
      `SMOKE_PASSWORD=${password}`,
      `SMOKE_USER_ID=${user.id}`,
      `SMOKE_PRACTICE_ID=${practice.id}`,
      '',
    ].join('\n'),
    'utf-8'
  );
  chmodSync(SMOKE_ENV_PATH, 0o600);

  console.log(`[prod-smoke] user=${user.id} practice=${practice.id}`);
  console.log(`[prod-smoke] credentials written to ${SMOKE_ENV_PATH} (chmod 600)`);
}

main()
  .catch((err) => {
    console.error('[prod-smoke] provision FAILED:', err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
