// ============================================================================
// Per-EHR clipboard formatters (T-M7)
// ----------------------------------------------------------------------------
// Doctors paste these strings into their EHR's note field. Each target
// has its own formatting quirks — Epic eats markdown, Athena loves it,
// Cerner wants plain text with visible dividers, eClinicalWorks expects
// single-letter S/O/A/P section prefixes.
//
// All five functions are pure — no Prisma, no Date.now(), no LLM. That
// keeps the unit tests deterministic + lets the client call them from
// its own "Copy this section" buttons without a round-trip.
// ============================================================================

import type { VisitExportData } from './visit-export';
import { prescriptionOneLine } from './visit-export';

export type EhrFormat =
  | 'epic'
  | 'athena'
  | 'cerner'
  | 'eclinicalworks'
  | 'generic';

interface FormatterOptions {
  /** Set false to skip the "Draft by QuillMD…" footer — useful
   *  when a section is copied on its own and the footer would be noise. */
  includeFooter?: boolean;
}

export function formatForEhr(
  format: EhrFormat,
  data: VisitExportData,
  opts: FormatterOptions = {}
): string {
  switch (format) {
    case 'epic':
      return formatForEpic(data, opts);
    case 'athena':
      return formatForAthena(data, opts);
    case 'cerner':
      return formatForCerner(data, opts);
    case 'eclinicalworks':
      return formatForEclinicalworks(data, opts);
    default:
      return formatGeneric(data, opts);
  }
}

// ---------------------------------------------------------------------------
// Shared helpers
// ---------------------------------------------------------------------------

function formatHumanDate(d: Date): string {
  // Example: "Apr 19, 2026". No locale — deterministic for tests.
  const months = [
    'Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec',
  ];
  return `${months[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`;
}

function patientHeader(data: VisitExportData): { name: string; date: string } {
  return {
    name: data.patientName?.trim() || 'Anonymous patient',
    date: formatHumanDate(data.signedAt ?? data.createdAt),
  };
}

function formatSignedBy(data: VisitExportData, lineBreak = '\n'): string {
  const name = data.clinicianName ?? 'Clinician';
  if (data.signedAt) {
    return `Signed electronically by ${name} on ${formatHumanDate(
      data.signedAt
    )}.${lineBreak}Draft generated by QuillMD. Clinician reviewed and signed.`;
  }
  return `Draft generated by QuillMD. Awaiting clinician signature.`;
}

/** Strip markdown bold (** **) and section-header hashes (## ) for EHRs
 *  that don't render markdown. Preserves text content, newlines, bullets.
 *  Structure-aware notes (GitHub tables + task lists) are flattened to
 *  ASCII first so Epic/Cerner/eCW paste degrades identically — an EHR
 *  plain-text field has an unknown font stack, so `[x]`/`[ ]` and
 *  `Header: value` lines are the safe wire format (never raw pipes). */
function stripMarkdown(s: string): string {
  return flattenTasks(flattenTables(s))
    .replace(/^#{1,6}\s+/gm, '') // ## Heading → Heading
    .replace(/\*\*(.+?)\*\*/g, '$1') // **bold** → bold
    .replace(/(?<!\*)\*(?!\*)(.+?)\*(?!\*)/g, '$1'); // *italic* → italic
}

const TABLE_ROW_RE = /^\s*\|.*\|\s*$/;
const TABLE_SEPARATOR_ROW_RE = /^\s*\|[\s:|-]+\|\s*$/;
const TASK_LINE_RE = /^(\s*)[-*]\s+\[( |x|X)\]\s+(.*)$/;

function parseTableRow(line: string): string[] {
  return line
    .trim()
    .replace(/^\|/, '')
    .replace(/\|$/, '')
    .split('|')
    .map((c) => c.trim());
}

/** Flatten GitHub-style markdown tables into plain lines an EHR text
 *  field can hold. A 2-column table collapses to `label: value` (the
 *  familiar shape today's parse already emits); wider tables zip the
 *  header with each body row → `Header1: cell1 · Header2: cell2`.
 *  Separator rows (|---|:---|) are dropped. A table with no body rows
 *  degrades to a single `Header1 · Header2` line so nothing is silently
 *  lost. Prose-only text (no pipe rows) passes through byte-identically. */
export function flattenTables(s: string): string {
  const lines = s.split('\n');
  const out: string[] = [];
  let buf: string[] = [];
  const flush = () => {
    if (buf.length === 0) return;
    const rows = buf
      .filter((l) => !TABLE_SEPARATOR_ROW_RE.test(l))
      .map(parseTableRow);
    buf = [];
    if (rows.length === 0) return;
    const [header, ...body] = rows;
    if (body.length === 0) {
      out.push(header.join(' · '));
      return;
    }
    for (const cells of body) {
      if (header.length === 2) {
        // 2-column table → `cell1: cell2` (label/value), matching the
        // shape today's parse produces so EHR paste stays familiar.
        out.push(`${cells[0] ?? ''}: ${cells[1] ?? ''}`);
        continue;
      }
      out.push(header.map((h, i) => `${h}: ${cells[i] ?? ''}`).join(' · '));
    }
  };
  for (const raw of lines) {
    if (TABLE_ROW_RE.test(raw)) {
      buf.push(raw);
      continue;
    }
    flush();
    out.push(raw);
  }
  flush();
  return out.join('\n');
}

/** Flatten task-list rows to ASCII: `- [x] Foo` → `[x] Foo`,
 *  `- [ ] Foo` → `[ ] Foo`. Unchecked options stay VISIBLE — an
 *  unchecked "chaperone offered" is a meaningful clinical fact, not
 *  noise. Indentation is preserved. Prose passes through unchanged. */
export function flattenTasks(s: string): string {
  return s
    .split('\n')
    .map((line) => {
      const m = line.match(TASK_LINE_RE);
      if (!m) return line;
      const mark = m[2].toLowerCase() === 'x' ? 'x' : ' ';
      return `${m[1]}[${mark}] ${m[3]}`;
    })
    .join('\n');
}

function icdSection(data: VisitExportData, label = 'DIAGNOSES'): string[] {
  if (data.icdCodes.length === 0) return [];
  const lines: string[] = [`${label}:`];
  for (const c of data.icdCodes) {
    lines.push(`  ${c.code} — ${c.description}`);
  }
  return lines;
}

function cptSection(data: VisitExportData, label = 'PROCEDURES / E&M'): string[] {
  const lines: string[] = [];
  const any = data.em || data.procedures.length || data.modifiers.length;
  if (!any) return [];
  lines.push(`${label}:`);
  if (data.em) {
    lines.push(`  ${data.em.code} — ${data.em.description}`);
  }
  for (const p of data.procedures) {
    lines.push(`  ${p.code} — ${p.description}`);
  }
  for (const m of data.modifiers) {
    lines.push(`  Modifier -${m.code}: ${m.rationale}`);
  }
  return lines;
}

function rxSection(data: VisitExportData, label = 'MEDICATIONS'): string[] {
  if (data.prescriptions.length === 0) return [];
  const lines: string[] = [`${label}:`];
  for (const rx of data.prescriptions) {
    lines.push(`  ${prescriptionOneLine(rx)}`);
  }
  if (data.rxWarnings.length > 0) {
    lines.push('  --- Rx warnings (review before sending):');
    for (const w of data.rxWarnings) {
      lines.push(`    [${w.severity.toUpperCase()}] ${w.rx_drug}: ${w.message}`);
    }
  }
  return lines;
}

function referralsSection(data: VisitExportData, label = 'REFERRALS'): string[] {
  if (data.referrals.length === 0) return [];
  const lines: string[] = [`${label}:`];
  for (const r of data.referrals) {
    lines.push(`  → ${r.to} (${r.urgency}) — ${r.reason}`);
  }
  return lines;
}

// ---------------------------------------------------------------------------
// Epic — double-newline between sections. ALL-CAPS headers.
// No markdown (Epic's rich-text editor ignores asterisks but renders
// hashes as literal text). Rx in single-line format.
// ---------------------------------------------------------------------------

export function formatForEpic(
  data: VisitExportData,
  opts: FormatterOptions = {}
): string {
  const { name, date } = patientHeader(data);
  const soap = stripMarkdown(data.soapText).trim();
  const sections: string[][] = [
    [`PATIENT: ${name}`, `DATE: ${date}`],
    [soap],
    icdSection(data),
    cptSection(data),
    rxSection(data),
    referralsSection(data),
  ];
  if (opts.includeFooter !== false) {
    sections.push([formatSignedBy(data, '\n')]);
  }
  return sections
    .filter((lines) => lines.length > 0)
    .map((lines) => lines.join('\n'))
    .join('\n\n');
}

// ---------------------------------------------------------------------------
// Athena — markdown-friendly. Bold headers, bulleted diagnoses, preserves
// blank lines.
// ---------------------------------------------------------------------------

export function formatForAthena(
  data: VisitExportData,
  opts: FormatterOptions = {}
): string {
  const { name, date } = patientHeader(data);
  const body: string[] = [
    `**Patient:** ${name}  `,
    `**Date:** ${date}`,
    '',
    // SOAP arrives as markdown-ish already — leave it.
    data.soapText.trim(),
  ];
  if (data.icdCodes.length) {
    body.push('', '**Diagnoses**');
    for (const c of data.icdCodes) {
      body.push(`- \`${c.code}\` ${c.description}`);
    }
  }
  const cptLines = cptSection(data, 'Procedures / E&M');
  if (cptLines.length) {
    body.push('', `**${cptLines[0].replace(':', '')}**`);
    for (const l of cptLines.slice(1)) body.push(`- ${l.trim()}`);
  }
  const rxLines = rxSection(data, 'Medications');
  if (rxLines.length) {
    body.push('', `**${rxLines[0].replace(':', '')}**`);
    for (const l of rxLines.slice(1)) body.push(`- ${l.trim()}`);
  }
  const refLines = referralsSection(data, 'Referrals');
  if (refLines.length) {
    body.push('', `**${refLines[0].replace(':', '')}**`);
    for (const l of refLines.slice(1)) body.push(`- ${l.trim()}`);
  }
  if (opts.includeFooter !== false) {
    body.push('', '---', `_${formatSignedBy(data, ' ')}_`);
  }
  return body.join('\n');
}

// ---------------------------------------------------------------------------
// Cerner — plain text, visible "-----" dividers, no markdown.
// ---------------------------------------------------------------------------

export function formatForCerner(
  data: VisitExportData,
  opts: FormatterOptions = {}
): string {
  const { name, date } = patientHeader(data);
  const DIV = '-------------------------------------------------------------';
  const chunks: string[] = [
    `${name}  |  ${date}`,
    DIV,
    stripMarkdown(data.soapText).trim(),
  ];
  const pushSection = (heading: string, lines: string[]) => {
    if (lines.length === 0) return;
    chunks.push('', DIV, heading, ...lines.slice(1));
  };
  pushSection('DIAGNOSES', icdSection(data));
  pushSection('PROCEDURES / E&M', cptSection(data));
  pushSection('MEDICATIONS', rxSection(data));
  pushSection('REFERRALS', referralsSection(data));
  if (opts.includeFooter !== false) {
    chunks.push('', DIV, formatSignedBy(data, '\n'));
  }
  return chunks.join('\n');
}

// ---------------------------------------------------------------------------
// eClinicalWorks — single-letter S: O: A: P: prefixes. We infer by
// parsing the SOAP's markdown headings; if the headings are missing
// or in a different order, fall through to the generic format body.
// ---------------------------------------------------------------------------

export function formatForEclinicalworks(
  data: VisitExportData,
  opts: FormatterOptions = {}
): string {
  const { name, date } = patientHeader(data);
  const relabelled = relabelSoapForEcw(data.soapText);

  const chunks: string[] = [
    `${name} — ${date}`,
    '',
    relabelled.trim(),
  ];
  const pushSection = (label: string, lines: string[]) => {
    if (lines.length === 0) return;
    chunks.push('', `${label}:`, ...lines.slice(1));
  };
  pushSection('DX', icdSection(data));
  pushSection('CPT', cptSection(data));
  pushSection('RX', rxSection(data));
  pushSection('REFERRALS', referralsSection(data));
  if (opts.includeFooter !== false) {
    chunks.push('', formatSignedBy(data, '\n'));
  }
  return chunks.join('\n');
}

/** Rewrite "## Subjective" → "S:" etc. If a heading isn't present, the
 *  text passes through unchanged. */
function relabelSoapForEcw(soap: string): string {
  return soap
    .replace(/^##\s+Subjective\s*$/gim, 'S:')
    .replace(/^##\s+Objective\s*$/gim, 'O:')
    .replace(/^##\s+Assessment\s*$/gim, 'A:')
    .replace(/^##\s+Plan\s*$/gim, 'P:')
    // Strip **bold** markers elsewhere — eCW doesn't render them.
    .replace(/\*\*(.+?)\*\*/g, '$1');
}

// ---------------------------------------------------------------------------
// Generic — clean markdown-ish fallback. Works anywhere.
// ---------------------------------------------------------------------------

export function formatGeneric(
  data: VisitExportData,
  opts: FormatterOptions = {}
): string {
  const { name, date } = patientHeader(data);
  const out: string[] = [
    `Patient: ${name}`,
    `Date: ${date}`,
    '',
    data.soapText.trim(),
  ];
  const sections: { heading: string; lines: string[] }[] = [
    { heading: 'Diagnoses', lines: icdSection(data) },
    { heading: 'Procedures / E&M', lines: cptSection(data) },
    { heading: 'Medications', lines: rxSection(data) },
    { heading: 'Referrals', lines: referralsSection(data) },
  ];
  for (const s of sections) {
    if (s.lines.length === 0) continue;
    out.push('', s.heading, ...s.lines.slice(1));
  }
  if (opts.includeFooter !== false) {
    out.push('', '---', formatSignedBy(data, '\n'));
  }
  return out.join('\n');
}

// ---------------------------------------------------------------------------
// Section-only helpers — used by the "Copy this section" buttons on each
// tab. Each returns a plain-text view of a single section.
// ---------------------------------------------------------------------------

export function sectionSoap(data: VisitExportData): string {
  return stripMarkdown(data.soapText).trim();
}

export function sectionCodes(data: VisitExportData): string {
  const chunks = [
    ...icdSection(data),
    '',
    ...cptSection(data),
  ].filter((l) => l.length > 0);
  return chunks.join('\n').trim();
}

export function sectionRx(data: VisitExportData): string {
  return rxSection(data).join('\n');
}

export function sectionExtras(data: VisitExportData): string {
  const chunks: string[] = [];
  chunks.push(...referralsSection(data));
  if (data.patientSummary) {
    if (chunks.length) chunks.push('');
    chunks.push('PATIENT SUMMARY:', data.patientSummary.trim());
  }
  return chunks.join('\n').trim();
}
