import { describe, expect, it } from 'vitest';

import {
  assertTemplateTwinRecordOwner,
  assertTenantOwnedArtifactKey,
  createOutputArtifactKey,
  createSourceArtifactKey,
  isTemplateTwinRecordOwner,
  parseTemplateTwinArtifactKey,
  TemplateTwinArtifactNotFoundError,
} from '..';

const SHA_A = 'a'.repeat(64);
const SHA_B = 'b'.repeat(64);
const ID = () => 'artifact_opaque_01';

describe('Template Twin object-key ownership', () => {
  it('parses only opaque keys generated by the source/output builders', () => {
    const source = createSourceArtifactKey({
      practiceId: 'practice_1',
      lineageId: 'lineage_1',
      templateVersion: 2,
      sha256: SHA_A,
      idFactory: ID,
    });
    const output = createOutputArtifactKey({
      practiceId: 'practice_1',
      visitId: 'visit_1',
      manifestSha256: SHA_A,
      outputSha256: SHA_B,
      idFactory: ID,
    });

    expect(parseTemplateTwinArtifactKey(source)).toEqual({
      practiceId: 'practice_1',
      kind: 'source',
      sha256: SHA_A,
    });
    expect(parseTemplateTwinArtifactKey(output)).toEqual({
      practiceId: 'practice_1',
      kind: 'output',
      sha256: SHA_B,
    });
    expect(source).not.toContain('patient');
    expect(source).not.toContain('template.docx');
  });

  it('rejects traversal, extra segments, wrong tenant, and wrong artifact kind as opaque not-found', () => {
    const source = createSourceArtifactKey({
      practiceId: 'practice_1',
      lineageId: 'lineage_1',
      templateVersion: 1,
      sha256: SHA_A,
      idFactory: ID,
    });

    expect(parseTemplateTwinArtifactKey(source.replace('/sources/', '/../sources/'))).toBeNull();
    expect(parseTemplateTwinArtifactKey(`${source}/extra`)).toBeNull();
    expect(() =>
      assertTenantOwnedArtifactKey({
        objectKey: source,
        practiceId: 'practice_2',
        kind: 'source',
      })
    ).toThrow(TemplateTwinArtifactNotFoundError);
    expect(() =>
      assertTenantOwnedArtifactKey({
        objectKey: source,
        practiceId: 'practice_1',
        kind: 'output',
      })
    ).toThrow(TemplateTwinArtifactNotFoundError);
  });
});

describe('Template Twin record ownership', () => {
  const actor = { userId: 'doctor_1', practiceId: 'practice_1' };

  it('requires both practice and physician ownership', () => {
    expect(
      isTemplateTwinRecordOwner(actor, {
        practiceId: 'practice_1',
        doctorId: 'doctor_1',
      })
    ).toBe(true);
    expect(
      isTemplateTwinRecordOwner(actor, {
        practiceId: 'practice_2',
        doctorId: 'doctor_1',
      })
    ).toBe(false);
    expect(
      isTemplateTwinRecordOwner(actor, {
        practiceId: 'practice_1',
        doctorId: 'doctor_2',
      })
    ).toBe(false);
  });

  it('supports source-artifact uploader ownership and fails opaquely', () => {
    expect(
      isTemplateTwinRecordOwner(actor, {
        practiceId: 'practice_1',
        uploadedById: 'doctor_1',
      })
    ).toBe(true);
    expect(() =>
      assertTemplateTwinRecordOwner(actor, {
        practiceId: 'practice_1',
        uploadedById: 'doctor_2',
      })
    ).toThrow(TemplateTwinArtifactNotFoundError);
  });
});
